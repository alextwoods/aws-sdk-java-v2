"""Writes the Library_Integration_Analysis (design D.7, Requirements 38.1 and 38.2) from its inputs.

Usage: library_integration_analysis.py [--check | --self-test] [--yaml PATH] [--size-report PATH] [--jmh PATH]
                                       [--markdown PATH]

Reads, in docs/design/schema-serde/:
  library-integration.yaml       the seven subjects; the file's header describes its format and keys
  size-report.md                 the Libraries rows (Requirement 38.2), generated by test/size-report
  library-integration-jmh.json   the JMH JSON result (-rf json) of S3EventNotificationBenchmark
and writes docs/design/schema-serde/library-integration-analysis.md.

  --check      Write nothing; exit with status 1 when an input is invalid or the Markdown differs from the generated
               output.
  --self-test  Run the unit tests below against fixture data.

Validation: each of the seven subject ids is present exactly once, in D.7 order; compatibility, directions and
recommendation are in the Requirement 38 vocabulary; required fields are non-empty; affected_public_types is empty
exactly when the compatibility is "none"; every size_report_library has a Libraries row and every benchmark has
results for both implementations; and an entry whose measured direction differs from its expected direction explains
it in size_note or perf_note.

Measured directions:
  size  from the compressed JAR change of the Libraries row: "increase" for a library new in the feature build,
        "neutral" when the change is at most SIZE_NEUTRAL_PCT of the Baseline_Build JAR, otherwise the sign.
  time  from the SCHEMA/LEGACY ratio of the average time per operation, for every operation and sample set:
        "neutral" when every ratio is within PERF_NEUTRAL_PCT of 1, "decrease" or "increase" when every ratio is
        below or above that band, "mixed" otherwise.
A JMH result with fewer warmup or measurement iterations or forks than the benchmark's class defaults is reported as
PRELIMINARY, with the command for the full run.
"""
import collections
import difflib
import json
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, SCRIPT_DIR)
import racecar_decisions as rd  # noqa: E402

REPO_ROOT = os.path.normpath(os.path.join(SCRIPT_DIR, "..", ".."))
DOCS_DIR = os.path.join(REPO_ROOT, "docs", "design", "schema-serde")
DEFAULT_YAML = os.path.join(DOCS_DIR, "library-integration.yaml")
DEFAULT_SIZE_REPORT = os.path.join(DOCS_DIR, "size-report.md")
DEFAULT_JMH = os.path.join(DOCS_DIR, "library-integration-jmh.json")
DEFAULT_MARKDOWN = os.path.join(DOCS_DIR, "library-integration-analysis.md")

# The seven subjects of Requirement 38.1, in the order of design D.7.
SUBJECT_IDS = (
    "s3-event-notifications", "sns-message-manager", "sqs-message-bodies", "lambda-event-payloads",
    "dynamodb-enhanced-client", "iam-policy-builder", "json-media-type-strings",
)
COMPATIBILITY = ("none", "additive", "breaking")
DIRECTIONS = ("increase", "decrease", "neutral")
RECOMMENDATIONS = ("Prototype in phase 3", "Defer to a later phase", "Do not adopt")

REQUIRED = ("id", "subject", "current_serde", "proposed_use", "compatibility", "affected_public_types",
            "size_direction", "size_estimate", "perf_direction", "perf_estimate", "recommendation", "rationale")
OPTIONAL = ("compatibility_note", "size_report_library", "size_confirmation", "size_note", "benchmark",
            "perf_confirmation", "perf_note", "task", "d7_compatibility", "note")
TEXT_KEYS = tuple(k for k in REQUIRED + OPTIONAL if k != "affected_public_types")

SIZE_NEUTRAL_PCT = 2.0
PERF_NEUTRAL_PCT = 5.0

BENCHMARK_PACKAGE = "software.amazon.awssdk.benchmark.schema."
LEGACY, SCHEMA = "LEGACY", "SCHEMA"
ALLOC_METRIC = "gc.alloc.rate.norm"
# The class defaults of the benchmarks (@Warmup(iterations = 5, time = 2), @Measurement(iterations = 5, time = 2),
# @Fork(2)): a run below these is preliminary.
FULL_RUN = {"warmupIterations": 5, "measurementIterations": 5, "forks": 2}
FULL_RUN_COMMAND = ("cd test/sdk-standard-benchmarks && java -jar target/benchmarks.jar {benchmark} -prof gc "
                    "-rf json -rff ../../docs/design/schema-serde/library-integration-jmh.json")

SIZE_SECTION = "## Libraries (Requirement 38.2)"
SIZE_ROW = re.compile(
    r"^\| (?P<name>.+) \(`(?P<id>[^`]+)`\) \| (?P<status>[^|]+?) "
    r"\| (?P<jar_before>[\d,]+) → (?P<jar_after>[\d,]+) \| [^|]+ "
    r"\| (?P<class_before>[\d,]+) → (?P<class_after>[\d,]+) \| [^|]+ "
    r"\| (?P<count_before>[\d,]+) → (?P<count_after>[\d,]+) \|$")


class InvalidAnalysis(Exception):
    pass


# ==================== inputs ====================

def parse_yaml(path):
    try:
        return rd.parse(path, REQUIRED + OPTIONAL)
    except rd.InvalidDecisions as e:
        raise InvalidAnalysis(str(e))


def parse_size_report(text):
    """The Libraries rows of size-report.md, keyed by artifactId."""
    rows = collections.OrderedDict()
    lines = text.splitlines()
    if SIZE_SECTION not in lines:
        raise InvalidAnalysis("size-report.md has no %r section; regenerate it with test/size-report" % SIZE_SECTION)
    for line in lines[lines.index(SIZE_SECTION) + 1:]:
        if line.startswith("## "):
            break
        match = SIZE_ROW.match(line)
        if match:
            row = {k: (int(v.replace(",", "")) if k not in ("name", "id", "status") else v)
                   for k, v in match.groupdict().items()}
            rows[row["id"]] = row
    return rows


def parse_jmh(results):
    """{benchmark class simple name: {"rows": [...], "settings": {...}}} from a JMH JSON result list."""
    benchmarks = collections.OrderedDict()
    for result in results:
        name = result["benchmark"]
        if not name.startswith(BENCHMARK_PACKAGE):
            continue
        cls, method = name[len(BENCHMARK_PACKAGE):].rsplit(".", 1)
        params = dict(result.get("params", {}))
        implementation = params.pop("implementation", None)
        if implementation not in (LEGACY, SCHEMA):
            raise InvalidAnalysis("%s: params.implementation is %r, not LEGACY or SCHEMA" % (name, implementation))
        entry = benchmarks.setdefault(cls, {"cells": collections.OrderedDict(), "settings": []})
        key = (method,) + tuple("%s=%s" % kv for kv in sorted(params.items()))
        alloc = result.get("secondaryMetrics", {}).get(ALLOC_METRIC)
        entry["cells"].setdefault(key, {})[implementation] = {
            "score": result["primaryMetric"]["score"],
            "unit": result["primaryMetric"]["scoreUnit"],
            "alloc": None if alloc is None else alloc["score"],
        }
        entry["settings"].append({k: result.get(k) for k in (
            "jmhVersion", "jdkVersion", "vmName", "vmVersion", "forks", "warmupIterations", "warmupTime",
            "measurementIterations", "measurementTime")})
    for cls, entry in benchmarks.items():
        for key, cell in entry["cells"].items():
            if set(cell) != {LEGACY, SCHEMA}:
                raise InvalidAnalysis("%s %s has no %s result" % (cls, " ".join(key),
                                                                  ({LEGACY, SCHEMA} - set(cell)).pop()))
    return benchmarks


# ==================== measured directions ====================

def size_direction(row):
    before, after = row["jar_before"], row["jar_after"]
    if before == 0:
        return "increase"
    change = after - before
    if abs(change) * 100.0 <= SIZE_NEUTRAL_PCT * before:
        return "neutral"
    return "increase" if change > 0 else "decrease"


def perf_direction(cells):
    signs = set()
    for cell in cells.values():
        ratio = cell[SCHEMA]["score"] / cell[LEGACY]["score"]
        if abs(ratio - 1) * 100.0 <= PERF_NEUTRAL_PCT:
            signs.add("neutral")
        else:
            signs.add("decrease" if ratio < 1 else "increase")
    return signs.pop() if len(signs) == 1 else "mixed"


def is_preliminary(settings):
    return any((s.get(k) or 0) < v for s in settings for k, v in FULL_RUN.items())


# ==================== validation ====================

def _is_text(value):
    return isinstance(value, str) and value.strip() != "" and "\n" not in value


def validate(entries, size_rows, benchmarks):
    errors = []
    seen = collections.Counter(e.get("id") for e in entries)
    for entry in entries:
        where = "line %d (%s)" % (entry["_line"], entry.get("id", "no id"))
        for key in TEXT_KEYS:
            if (key in REQUIRED or key in entry) and not _is_text(entry.get(key)):
                errors.append("%s: %s is missing or empty" % (where, key))
        if entry.get("id") is not None and entry["id"] not in SUBJECT_IDS:
            errors.append("%s: %r is not one of the seven subject ids" % (where, entry["id"]))
        for key, vocabulary in (("compatibility", COMPATIBILITY), ("size_direction", DIRECTIONS),
                                ("perf_direction", DIRECTIONS), ("recommendation", RECOMMENDATIONS)):
            if entry.get(key) is not None and entry[key] not in vocabulary:
                errors.append("%s: %s %r is not one of %s" % (where, key, entry[key], ", ".join(vocabulary)))
        types = entry.get("affected_public_types")
        if not isinstance(types, list) or not all(_is_text(t) for t in types):
            errors.append("%s: affected_public_types must be a list of one-line strings" % where)
        elif (entry.get("compatibility") == "none") != (not types):
            errors.append("%s: affected_public_types must be empty exactly when the compatibility is none" % where)
        if "d7_compatibility" in entry:
            if entry["d7_compatibility"] not in COMPATIBILITY or entry["d7_compatibility"] == entry.get("compatibility"):
                errors.append("%s: d7_compatibility must be a compatibility other than %r"
                              % (where, entry.get("compatibility")))
            if "note" not in entry:
                errors.append("%s: a compatibility that differs from D.7 needs a note" % where)

        library = entry.get("size_report_library")
        if library is not None:
            if library not in size_rows:
                errors.append("%s: size-report.md has no Libraries row for %r" % (where, library))
            elif size_direction(size_rows[library]) != entry.get("size_direction") and "size_note" not in entry:
                errors.append("%s: the measured size change (%s) differs from size_direction %r; explain it in "
                              "size_note" % (where, size_direction(size_rows[library]), entry.get("size_direction")))
        elif "size_note" in entry:
            errors.append("%s: size_note needs a size_report_library" % where)
        benchmark = entry.get("benchmark")
        if benchmark is not None:
            if benchmark not in benchmarks:
                errors.append("%s: the JMH result has no %s results" % (where, benchmark))
            elif (perf_direction(benchmarks[benchmark]["cells"]) != entry.get("perf_direction")
                  and "perf_note" not in entry):
                errors.append("%s: the measured time change (%s) differs from perf_direction %r; explain it in "
                              "perf_note" % (where, perf_direction(benchmarks[benchmark]["cells"]),
                                             entry.get("perf_direction")))
        elif "perf_note" in entry:
            errors.append("%s: perf_note needs a benchmark" % where)

    for subject_id in SUBJECT_IDS:
        if seen[subject_id] == 0:
            errors.append("subject %r has no entry" % subject_id)
        elif seen[subject_id] > 1:
            errors.append("subject %r has %d entries" % (subject_id, seen[subject_id]))
    if not errors and [e["id"] for e in entries] != list(SUBJECT_IDS):
        errors.append("the entries must be in the order of design D.7: %s" % ", ".join(SUBJECT_IDS))
    if errors:
        raise InvalidAnalysis("\n".join(errors))
    return entries


# ==================== rendering ====================

def _cell(text):
    return text.replace("|", "\\|")


def _sentence(text):
    return text if text.endswith(".") else text + "."


def _n(value):
    return "{:,}".format(value)


def _signed(value):
    return ("+" if value > 0 else "") + _n(value)


def _pct(change, base):
    return "" if base == 0 else " (%+.1f%%)" % (100.0 * change / base)


def _num(value):
    return "%.3f" % value if value < 10 else "{:,.1f}".format(value)


def _ratio_change(new, old):
    return "%+.1f%%" % (100.0 * (new - old) / old)


def _type(text):
    """A type name in code font; text after the name, or an item in parentheses, stays plain."""
    if text.startswith("("):
        return text
    name, sep, rest = text.partition(" ")
    return "`%s`%s%s" % (name, sep, rest)


def _types(entry):
    types = entry["affected_public_types"]
    return "none" if not types else ", ".join(_type(t) for t in types)


def _measured_size(entry, size_rows):
    library = entry.get("size_report_library")
    if library is None:
        return None
    row = size_rows[library]
    change = row["jar_after"] - row["jar_before"]
    return "%s: JAR %s → %s B, %s%s" % (size_direction(row), _n(row["jar_before"]), _n(row["jar_after"]),
                                         _signed(change), _pct(change, row["jar_before"]))


def _measured_perf(entry, benchmarks):
    benchmark = entry.get("benchmark")
    if benchmark is None:
        return None
    data = benchmarks[benchmark]
    label = "PRELIMINARY " if is_preliminary(data["settings"]) else ""
    return "%s%s (`%s`)" % (label, perf_direction(data["cells"]), benchmark)


def render(entries, size_rows, benchmarks):
    preliminary = any(is_preliminary(benchmarks[e["benchmark"]]["settings"]) for e in entries if "benchmark" in e)
    counts = collections.Counter(e["recommendation"] for e in entries)
    out = [
        "<!-- Generated by scripts/schema-serde/library_integration_analysis.py from library-integration.yaml, "
        "size-report.md and library-integration-jmh.json. Do not edit. -->",
        "",
        "# Library_Integration_Analysis",
        "",
        "Where Documents and Type_Registries can improve the SDK's higher-level libraries (design D.7, Requirements "
        "38.1 and 38.2): one entry per subject, with its current serde (a), the proposed use of Schemas, Documents or "
        "Type_Registries (b), the compatibility impact on the library's public API (c), the expected artifact-size "
        "(d) and performance (e) effects, and a recommendation. Where a library was prototyped, the measured size "
        "comes from the Libraries rows of `size-report.md` and the measured time from `library-integration-jmh.json`.",
        "",
        "Edit `library-integration.yaml` and regenerate this file with "
        "`python3 scripts/schema-serde/library_integration_analysis.py`. `LibraryIntegrationAnalysisTest` "
        "(`test/architecture-tests`) runs the script's `--check` mode and fails when this file is out of date or an "
        "input is invalid.",
        "",
    ]
    if preliminary:
        out += ["> **PRELIMINARY.** The benchmark numbers below come from a smoke run (fewer iterations and forks "
                "than the benchmark's defaults). Performance measurements are deferred; rerun at full settings "
                "before relying on them (see Benchmark).", ""]
    out += ["## Summary", "",
            "| # | Subject | Compatibility (c) | Size (d): expected | Size (d): measured | Time (e): expected | "
            "Time (e): measured | Recommendation |",
            "|---|---|---|---|---|---|---|---|"]
    for number, e in enumerate(entries, 1):
        out.append("| %d | %s | %s | %s | %s | %s | %s | **%s** |" % (
            number, _cell(e["subject"]), e["compatibility"], e["size_direction"],
            _cell(_measured_size(e, size_rows) or "—"), e["perf_direction"],
            _cell(_measured_perf(e, benchmarks) or "—"), e["recommendation"]))
    out += ["", "| Recommendation | Subjects |", "|---|---:|"]
    out += ["| %s | %d |" % (r, counts[r]) for r in RECOMMENDATIONS]
    out += ["| Total | %d |" % len(entries), "", "## Entries", ""]
    for number, e in enumerate(entries, 1):
        out += ["### %d. %s" % (number, e["subject"]), ""]
        out.append("- **Recommendation: %s.** %s" % (e["recommendation"], _sentence(e["rationale"])))
        if "task" in e:
            out.append("- **Prototype:** task %s." % e["task"])
        out.append("- **(a) Current serde:** %s" % _sentence(e["current_serde"]))
        out.append("- **(b) Proposed use:** %s" % _sentence(e["proposed_use"]))
        compatibility = "- **(c) Compatibility:** %s. Affected public types: %s." % (e["compatibility"], _types(e))
        if "compatibility_note" in e:
            compatibility += " " + _sentence(e["compatibility_note"])
        out.append(compatibility)
        out.append(_effect("(d) Size", e["size_direction"], e["size_estimate"], _measured_size(e, size_rows),
                           e.get("size_confirmation"), e.get("size_note")))
        out.append(_effect("(e) Time", e["perf_direction"], e["perf_estimate"], _measured_perf(e, benchmarks),
                           e.get("perf_confirmation"), e.get("perf_note")))
        if "note" in e:
            out.append("- **Note:** %s" % _sentence(e["note"]))
        out.append("")
    out += _size_section(entries, size_rows)
    for benchmark in sorted({e["benchmark"] for e in entries if "benchmark" in e}):
        out += _benchmark_section(benchmark, benchmarks[benchmark])
    changed = [e for e in entries if "d7_compatibility" in e]
    out += ["## Differences from the design D.7 table", "",
            "Where the implementation differs from D.7, the entries above record the implementation. Measured "
            "directions that differ from the expected ones are explained in each entry's Size or Time line.", ""]
    if changed:
        out += ["| Subject | D.7 compatibility | Compatibility |", "|---|---|---|"]
        out += ["| %s | %s | %s |" % (_cell(e["subject"]), e["d7_compatibility"], e["compatibility"]) for e in changed]
        out.append("")
    mismatched = [e for e in entries if "size_note" in e or "perf_note" in e]
    if mismatched:
        out += ["Entries whose measurement differs from the estimate: %s." % ", ".join(
            e["subject"].split(" (")[0] for e in mismatched), ""]
    out += ["## Method", "",
            "- **Size (d).** The measured direction comes from the change in compressed JAR bytes in the "
            "`size-report.md` Libraries row: increase for a library that is new in the feature build, neutral when "
            "the change is at most %.0f%% of the Baseline_Build JAR, otherwise the sign of the change. The "
            "Baseline_Build is the merge base of this branch, built with the same JDK and compiler options "
            "(Requirement 36.7)." % SIZE_NEUTRAL_PCT,
            "- **Time (e).** The measured direction comes from the SCHEMA/LEGACY ratio of the average time per "
            "operation, over every operation and sample set: neutral when every ratio is within %.0f%% of 1, "
            "decrease or increase when every ratio is below or above that band, and mixed otherwise." %
            PERF_NEUTRAL_PCT,
            "- **PRELIMINARY.** A JMH result with fewer warmup or measurement iterations or forks than the "
            "benchmark's class defaults (%d, %d and %d) is a smoke run." % (
                FULL_RUN["warmupIterations"], FULL_RUN["measurementIterations"], FULL_RUN["forks"])]
    return "\n".join(out) + "\n"


def _effect(label, direction, estimate, measured, confirmation, note):
    text = "- **%s:** expected %s. %s" % (label, direction, _sentence(estimate))
    if measured is not None:
        text += " Measured: %s." % measured
    elif confirmation is not None:
        text += " To be confirmed by: %s" % _sentence(confirmation)
    if note is not None:
        text += " %s" % _sentence(note)
    return text


def _size_section(entries, size_rows):
    used = collections.OrderedDict()
    for e in entries:
        if "size_report_library" in e:
            used.setdefault(e["size_report_library"], []).append(e["subject"].split(" (")[0])
    if not used:
        return []
    out = ["## Size measurements", "",
           "From the Libraries rows of `size-report.md` (test/size-report). Bytes; Baseline_Build → feature build.",
           "",
           "| Library | Entries | Status | Compressed JAR | Change | Uncompressed class bytes | Change | "
           "`.class` entries | Measured direction |",
           "|---|---|---|---|---|---|---|---|---|"]
    for library, subjects in used.items():
        row = size_rows[library]
        jar = row["jar_after"] - row["jar_before"]
        classes = row["class_after"] - row["class_before"]
        out.append("| `%s` | %s | %s | %s → %s | %s%s | %s → %s | %s%s | %s → %s | %s |" % (
            library, _cell(", ".join(subjects)), row["status"], _n(row["jar_before"]), _n(row["jar_after"]),
            _signed(jar), _pct(jar, row["jar_before"]), _n(row["class_before"]), _n(row["class_after"]),
            _signed(classes), _pct(classes, row["class_before"]), _n(row["count_before"]), _n(row["count_after"]),
            size_direction(row)))
    return out + [""]


def _benchmark_section(benchmark, data):
    settings = data["settings"][0]
    preliminary = is_preliminary(data["settings"])
    out = ["## Benchmark: `%s`%s" % (benchmark, " (PRELIMINARY)" if preliminary else ""), "",
           "`test/sdk-standard-benchmarks`, package `benchmark.schema`. LEGACY is the previous reader and writer, "
           "SCHEMA the library on schemas; one operation reads or writes every notification of the sample set "
           "once. B/op is `%s` from `-prof gc`." % ALLOC_METRIC, "",
           "Run: JMH %s, %s %s (JDK %s); %s warmup × %s and %s measurement × %s iterations, %s fork(s)." % (
               settings["jmhVersion"], settings["vmName"], settings["vmVersion"], settings["jdkVersion"],
               settings["warmupIterations"], settings["warmupTime"], settings["measurementIterations"],
               settings["measurementTime"], settings["forks"]), ""]
    if preliminary:
        out += ["Smoke settings: the numbers show a direction only. Full run (class defaults) from the repository "
                "root, after `mvn clean install -pl :sdk-standard-benchmarks -P quick`, then regenerate this file:",
                "", "```bash", FULL_RUN_COMMAND.format(benchmark=benchmark), "```", ""]
    unit = next(iter(data["cells"].values()))[LEGACY]["unit"].replace("us/", "µs/")
    out += ["| Operation | Parameters | LEGACY %s | SCHEMA %s | Change | LEGACY B/op | SCHEMA B/op | Change |" % (
        unit, unit), "|---|---|---:|---:|---:|---:|---:|---:|"]
    for key, cell in data["cells"].items():
        legacy, schema = cell[LEGACY], cell[SCHEMA]
        if legacy["alloc"] is None or schema["alloc"] is None:
            alloc = "— | — | —"
        else:
            alloc = "%s | %s | %s" % (_n(int(round(legacy["alloc"]))), _n(int(round(schema["alloc"]))),
                                      _ratio_change(schema["alloc"], legacy["alloc"]))
        out.append("| `%s` | %s | %s | %s | %s | %s |" % (
            key[0], ", ".join(key[1:]) or "—", _num(legacy["score"]), _num(schema["score"]),
            _ratio_change(schema["score"], legacy["score"]), alloc))
    return out + ["", "Measured time direction: %s." % perf_direction(data["cells"]), ""]


# ==================== main ====================

def load(yaml_path, size_report_path, jmh_path):
    entries = parse_yaml(yaml_path)
    with open(size_report_path, encoding="utf-8") as f:
        size_rows = parse_size_report(f.read())
    with open(jmh_path, encoding="utf-8") as f:
        try:
            benchmarks = parse_jmh(json.load(f))
        except (ValueError, KeyError, TypeError) as e:
            raise InvalidAnalysis("%s is not a JMH JSON result: %s" % (jmh_path, e))
    return validate(entries, size_rows, benchmarks), size_rows, benchmarks


def main(argv):
    args = argv[1:]
    if args[:1] == ["--self-test"]:
        return self_test()
    check = False
    paths = {"--yaml": DEFAULT_YAML, "--size-report": DEFAULT_SIZE_REPORT, "--jmh": DEFAULT_JMH,
             "--markdown": DEFAULT_MARKDOWN}
    while args:
        arg = args.pop(0)
        if arg == "--check" and not check:
            check = True
        elif arg in paths and args:
            paths[arg] = args.pop(0)
        else:
            sys.stderr.write(__doc__)
            return 2
    try:
        entries, size_rows, benchmarks = load(paths["--yaml"], paths["--size-report"], paths["--jmh"])
    except (InvalidAnalysis, OSError) as e:
        sys.stderr.write("The Library_Integration_Analysis inputs are invalid:\n%s\n" % e)
        return 1
    expected = render(entries, size_rows, benchmarks)
    markdown_path = paths["--markdown"]
    if check:
        actual = None
        if os.path.isfile(markdown_path):
            with open(markdown_path, encoding="utf-8", newline="") as f:
                actual = f.read()
        if actual != expected:
            sys.stderr.write("%s is out of date; regenerate it with "
                             "python3 scripts/schema-serde/library_integration_analysis.py\n" % markdown_path)
            sys.stderr.writelines(difflib.unified_diff((actual or "").splitlines(True), expected.splitlines(True),
                                                       "committed", "generated"))
            return 1
        print("%s is up to date (%d subjects)" % (markdown_path, len(entries)))
        return 0
    with open(markdown_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(expected)
    print("Wrote %s (%d subjects)" % (markdown_path, len(entries)))
    return 0


