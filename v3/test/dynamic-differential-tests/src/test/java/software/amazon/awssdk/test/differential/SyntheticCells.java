/**
 * The synthetic scenarios: for each of the seven synthetic services of {@code differential.smithy} (one per launch
 * protocol, generated by this module's build), one scenario per call shape the protocol supports, plus an output event
 * stream that ends with a modeled exception event. Together they run every supported cell of the matrix.
 *
 * <p>The Dynamic Client loads the JSON AST of the same IDL file the generator read, assembled once.
 */
final class SyntheticCells {
    static final String NAMESPACE = "example.differential";
    static final String XMLNS = "https://example.test/differential/";
    private static final String EVENT_STREAM = "application/vnd.amazon.eventstream";

    private static final Supplier<DynamicModel> MODEL = memoize(SyntheticCells::loadModel);

    private SyntheticCells() {
    }

    static List<Target> targets() {
        return List.of(target(Protocol.AWS_JSON_1_0, "JsonZero", "jsonzero"),
                       target(Protocol.AWS_JSON_1_1, "JsonOne", "jsonone"),
                       target(Protocol.RPCV2_CBOR, "Cbor", "cbor"),
                       target(Protocol.AWS_QUERY, "Query", "query"),
                       target(Protocol.EC2_QUERY, "Ec2", "ec2"),
                       target(Protocol.REST_JSON_1, "RestJson", "restjson"),
                       target(Protocol.REST_XML, "RestXml", "restxml"));
    }

    private static Target target(Protocol protocol, String sdkId, String prefix) {
        return new Target("synthetic:" + sdkId, protocol, ShapeId.fromParts(NAMESPACE, sdkId),
                          "software.amazon.awssdk.test.differential." + prefix, sdkId, prefix, MODEL);
    }

    static List<Scenario> scenarios() {
        List<Scenario> out = new ArrayList<>();
        for (Target target : targets()) {
            out.addAll(scenarios(target));
        }
        return out;
    }

    private static List<Scenario> scenarios(Target target) {
        Protocol protocol = target.protocol();
        boolean rest = protocol.rest();
        String echo = rest ? "RestEcho" : "Echo";
        String list = rest ? "RestListItems" : "ListItems";
        String status = rest ? "RestGetStatus" : "GetStatus";
        List<Scenario> out = new ArrayList<>();

        Map<String, Object> echoInput = map("name", "alpha beta/\u03b3", "count", 7, "flag", true,
                                            "when", Instant.parse("2024-05-06T07:08:09.123Z"),
                                            "data", new byte[] {'b', 0, (byte) 0xff},
                                            "tags", List.of("x", "y z"), "attrs", map("k1", "v1", "k2", "v&2"),
                                            "inner", map("label", "in", "level", 3), "color", "green", "rank", 2,
                                            "token", "token-0001");
        Map<String, Object> echoOutput = map("name", "echoed", "count", 42, "flag", false,
                                             "when", Instant.ofEpochSecond(1_700_000_000L),
                                             "tags", List.of("a", "b c"), "inner", map("label", "out", "level", 2),
                                             "color", "RED", "rank", 1);
        out.add(new ScenarioBuilder(target, CallShape.FINITE, echo).input(echoInput)
                    .reply(success(protocol, echo, echoOutput)).build());
        out.add(new ScenarioBuilder(target, CallShape.MODELED_ERROR, echo).input(echoInput)
                    .reply(error(protocol, 400, "Bad", map("message", "bad input", "reason", "invalid"))).build());
        String defaults = rest ? "RestDefaults" : "Defaults";
        out.add(new ScenarioBuilder(target, CallShape.FINITE, defaults).title("unset @default members")
                    .input(map("name", "d-1", "nested", map("label", "in")))
                    .reply(success(protocol, defaults, map("name", "d-1", "nested", map("label", "out"))))
                    .build());
        Reply unavailable = error(protocol, 503, "ServiceUnavailable", map("message", "try later"));
        out.add(new ScenarioBuilder(target, CallShape.UNMODELED_ERROR, echo).title("retried 503").input(echoInput)
                    .reply(unavailable, unavailable).requests(2).build());

        out.add(new ScenarioBuilder(target, CallShape.PAGINATED, list).input(map("maxResults", 2))
                    .reply(success(protocol, list, map("items", List.of("a", "b"), "nextToken", "t-2")),
                           success(protocol, list, map("items", List.of("c"))))
                    .requests(2).build());

        out.add(new ScenarioBuilder(target, CallShape.WAITER, status).waiter("StatusReady")
                    .input(map("id", "w 1"))
                    .reply(error(protocol, 400, "Bad", map("message", "not yet", "reason", "starting")),
                           success(protocol, status, map("status", "PENDING")),
                           success(protocol, status, map("status", "READY",
                                                         "detail", map("label", "d", "level", 5))))
                    .requests(3).build());

        if (rest) {
            byte[] upload = new byte[] {'u', 'p', 'l', 'o', 'a', 'd', ' ', 0, (byte) 0xff, '\n', 'e', 'n', 'd'};
            out.add(new ScenarioBuilder(target, CallShape.STREAMING_INPUT, "Upload")
                        .input(map("id", "blob 1", "meta", "m-1")).requestBody(upload)
                        .reply(Reply.of(200, new byte[0], "ETag", "\"etag-1\"")).build());
            byte[] download = new byte[] {'d', 'o', 'w', 'n', 0, (byte) 0xff, 'l', 'o', 'a', 'd'};
            out.add(new ScenarioBuilder(target, CallShape.STREAMING_OUTPUT, "Download")
                        .input(map("id", "blob 1", "part", 2))
                        .reply(Reply.of(200, download, "Content-Type", "application/octet-stream",
                                        "X-Size", String.valueOf(download.length)))
                        .build());
        }

        if (!protocol.query()) {
            String publish = rest ? "RestPublish" : "Publish";
            String watch = rest ? "RestWatch" : "Watch";
            Event note = new Event("note", map("text", "hello <world>", "level", 1, "tags", List.of("x")));
            Event chunk = new Event("chunk", map("kind", "bin", "seq", 2,
                                                 "data", new byte[] {1, 2, 3, (byte) 0xfe}));
            Map<String, Object> publishInput = rest ? map("id", "pub 1", "topic", "t-1") : map("name", "pub");
            Reply published = rest
                              ? success(protocol, publish, map("count", 2), "X-Version", "7")
                              : success(protocol, publish, map("count", 2));
            out.add(new ScenarioBuilder(target, CallShape.EVENT_STREAM_INPUT, publish).input(publishInput)
                        .inputEvents("events", "InEvents", note, chunk).reply(published).build());

            Map<String, Object> watchInput = rest ? map("id", "watch 1", "topic", "t-2")
                                                  : map("name", "watch", "inner", map("label", "i", "level", 1));
            List<byte[]> frames = new ArrayList<>();
            if (!rest) {
                frames.add(frame(protocol, "event", ":event-type", "initial-response", new LinkedHashMap<>(),
                                 payload(protocol, "WatchOutput", map("status", "open"))));
            }
            frames.add(eventFrame(protocol, note));
            frames.add(eventFrame(protocol, chunk));
            out.add(new ScenarioBuilder(target, CallShape.EVENT_STREAM_OUTPUT, watch).input(watchInput)
                        .reply(streamReply(protocol, frames)).events(2).build());

            List<byte[]> failing = new ArrayList<>(frames.subList(0, frames.size() - 1));
            failing.add(frame(protocol, "exception", ":exception-type", "failure", new LinkedHashMap<>(),
                              payload(protocol, "Failure", map("message", "stream failed", "reason", "r-1"))));
            out.add(new ScenarioBuilder(target, CallShape.EVENT_STREAM_OUTPUT, watch).title("modeled exception event")
                        .input(watchInput).reply(streamReply(protocol, failing)).expect(Outcome.MODELED_ERROR)
                        .events(1).build());
        }
        return out;
    }

    // -------------------------------------------------------------------------------------------------------------
    // Responses in each protocol's wire format

    static String contentType(Protocol protocol) {
        return switch (protocol) {
            case AWS_JSON_1_0 -> "application/x-amz-json-1.0";
            case AWS_JSON_1_1 -> "application/x-amz-json-1.1";
            case RPCV2_CBOR -> "application/cbor";
            case AWS_QUERY -> "text/xml";
            case EC2_QUERY -> "text/xml;charset=UTF-8";
            case REST_JSON_1 -> "application/json";
            case REST_XML -> "application/xml";
        };
    }

    /**
     * A modeled success of {@code operation}; {@code headers} are the members a REST output binds to headers. A
     * REST output's {@code name} member is bound to {@code X-Name}.
     */
    static Reply success(Protocol protocol, String operation, Map<String, Object> output, String... headers) {
        Map<String, Object> body = new LinkedHashMap<>(output);
        List<String> pairs = new ArrayList<>(List.of("Content-Type", contentType(protocol)));
        if (protocol == Protocol.RPCV2_CBOR) {
            pairs.addAll(List.of("smithy-protocol", "rpc-v2-cbor"));
        }
        if (protocol.rest() && body.containsKey("name")) {
            pairs.addAll(List.of("X-Name", body.remove("name").toString()));
        }
        pairs.addAll(List.of(headers));
        byte[] bytes = switch (protocol) {
            case AWS_JSON_1_0, AWS_JSON_1_1, REST_JSON_1 -> utf8(Values.json(body));
            case RPCV2_CBOR -> Values.cbor(body);
            case REST_XML -> utf8("<" + operation + "Output xmlns=\"" + XMLNS + "\">" + Values.xml(body) + "</"
                                  + operation + "Output>");
            case AWS_QUERY -> utf8("<" + operation + "Response xmlns=\"" + XMLNS + "\"><" + operation + "Result>"
                                   + Values.xml(body) + "</" + operation + "Result><ResponseMetadata><RequestId>"
                                   + "query-request</RequestId></ResponseMetadata></" + operation + "Response>");
            case EC2_QUERY -> utf8("<" + operation + "Response xmlns=\"" + XMLNS + "\"><requestId>ec2-request"
                                   + "</requestId>" + Values.xml(body) + "</" + operation + "Response>");
        };
        return Reply.of(200, bytes, pairs.toArray(String[]::new));
    }

    /** An error response with the error {@code code}: a modeled error when it names {@code Bad}. */
    static Reply error(Protocol protocol, int status, String code, Map<String, Object> members) {
        List<String> pairs = new ArrayList<>(List.of("Content-Type", contentType(protocol)));
        Map<String, Object> typed = new LinkedHashMap<>();
        typed.put("__type", NAMESPACE + "#" + code);
        typed.putAll(members);
        byte[] body = switch (protocol) {
            case AWS_JSON_1_0, AWS_JSON_1_1 -> utf8(Values.json(typed));
            case RPCV2_CBOR -> {
                pairs.addAll(List.of("smithy-protocol", "rpc-v2-cbor"));
                yield Values.cbor(typed);
            }
            case REST_JSON_1 -> {
                pairs.addAll(List.of("X-Amzn-ErrorType", code));
                yield utf8(Values.json(members));
            }
            case REST_XML, AWS_QUERY -> utf8("<ErrorResponse><Error><Type>Sender</Type><Code>" + code + "</Code>"
                                             + errorXml(members) + "</Error><RequestId>error-request</RequestId>"
                                             + "</ErrorResponse>");
            case EC2_QUERY -> utf8("<Response><Errors><Error><Code>" + code + "</Code>" + errorXml(members)
                                   + "</Error></Errors><RequestID>error-request</RequestID></Response>");
        };
        return Reply.of(status, body, pairs.toArray(String[]::new));
    }

    private static String errorXml(Map<String, Object> members) {
        StringBuilder out = new StringBuilder();
        members.forEach((name, value) -> {
            String element = name.equals("message") ? "Message" : name;
            out.append('<').append(element).append('>').append(Values.xmlEscape(value.toString())).append("</")
               .append(element).append('>');
        });
        return out.toString();
    }

    // -------------------------------------------------------------------------------------------------------------
    // Event streams

    private static Reply streamReply(Protocol protocol, List<byte[]> frames) {
        List<String> pairs = new ArrayList<>(List.of("Content-Type", EVENT_STREAM));
        if (protocol == Protocol.RPCV2_CBOR) {
            pairs.addAll(List.of("smithy-protocol", "rpc-v2-cbor"));
        }
        if (protocol.rest()) {
            pairs.addAll(List.of("X-Session", "s-1"));
        }
        return Reply.frames(200, frames, pairs.toArray(String[]::new));
    }

    /** One event frame: a {@code chunk}'s members as headers and blob payload, any other event as its payload. */
    private static byte[] eventFrame(Protocol protocol, Event event) {
        Map<String, Object> values = event.values();
        Map<String, HeaderValue> headers = new LinkedHashMap<>();
        if (event.member().equals("chunk")) {
            headers.put("kind", HeaderValue.ofString((String) values.get("kind")));
            headers.put("seq", HeaderValue.ofInteger((Integer) values.get("seq")));
            return frame("event", ":event-type", "chunk", "application/octet-stream", headers,
                         (byte[]) values.get("data"));
        }
        return frame(protocol, "event", ":event-type", event.member(), headers,
                     payload(protocol, "Note", values));
    }

    private static byte[] frame(Protocol protocol, String messageType, String typeHeader, String type,
                                Map<String, HeaderValue> members, byte[] payload) {
        return frame(messageType, typeHeader, type, payloadType(protocol), members, payload);
    }

    static byte[] frame(String messageType, String typeHeader, String type, String contentType,
                        Map<String, HeaderValue> members, byte[] payload) {
        Map<String, HeaderValue> headers = new LinkedHashMap<>();
        headers.put(":message-type", HeaderValue.ofString(messageType));
        headers.put(typeHeader, HeaderValue.ofString(type));
        headers.put(":content-type", HeaderValue.ofString(contentType));
        headers.putAll(members);
        return Values.bytes(MessageEncoder.encode(new Message(headers, payload)));
    }

    private static String payloadType(Protocol protocol) {
        return switch (protocol) {
            case RPCV2_CBOR -> "application/cbor";
            case REST_XML -> "application/xml";
            default -> "application/json";
        };
    }

    /** A structure payload: JSON, CBOR, or XML with {@code root} as its element. */
    private static byte[] payload(Protocol protocol, String root, Map<String, Object> members) {
        return switch (protocol) {
            case RPCV2_CBOR -> Values.cbor(members);
            case REST_XML -> utf8("<" + root + ">" + Values.xml(members) + "</" + root + ">");
            default -> utf8(Values.json(members));
        };
    }

    // -------------------------------------------------------------------------------------------------------------
    // The runtime model

    /** The JSON AST of the synthetic IDL model that aws-codegen-maven-plugin generated this module's clients from. */
    private static DynamicModel loadModel() {
        Path idl = Path.of(System.getProperty("v3.differential.syntheticModel", "src/main/smithy/differential.smithy"));
        ClassLoader classLoader = SyntheticCells.class.getClassLoader();
        Model model = Model.assembler(classLoader).discoverModels(classLoader)
                           .putProperty(ModelAssembler.ALLOW_UNKNOWN_TRAITS, true)
                           .addImport(idl)
                           .assemble().unwrap();
        String ast = Node.prettyPrintJson(ModelSerializer.builder().build().serialize(model));
        return DynamicModel.fromJsonAst(ast, idl.getFileName().toString());
    }

    /** {@code supplier}'s value, computed on first use and then shared. */
    static <T> Supplier<T> memoize(Supplier<T> supplier) {
        return new Supplier<>() {
            private T value;

            @Override
            public synchronized T get() {
                if (value == null) {
                    value = supplier.get();
                }
                return value;
            }
        };
    }
}
