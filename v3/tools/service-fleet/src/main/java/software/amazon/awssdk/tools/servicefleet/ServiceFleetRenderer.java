package software.amazon.awssdk.tools.servicefleet;

import java.util.List;
import java.util.function.Function;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Renders the fleet's Maven files from a {@link FleetPlan}: one {@code pom.xml} per service module, the module list
 * and pinned revision of the services aggregator ({@code v3/services/pom.xml}), and the service entries of the BOM.
 * The output depends only on the plan, so the gate can compare the files on disk with a fresh rendering.
 */
public final class ServiceFleetRenderer {

    /** First line of every generated service module POM's header comment; marks directories the writer owns. */
    public static final String GENERATED_MARKER = "Generated by v3/tools/service-fleet from services/service-fleet.json";

    static final String BEGIN = "<!-- service-fleet:begin (generated from services/service-fleet.json; do not edit) -->";
    static final String END = "<!-- service-fleet:end -->";
    static final String REVISION_PROPERTY = "aws.models.revision";

    private static final Pattern REGION = Pattern.compile("(?s)([ \\t]*)" + Pattern.quote(BEGIN) + ".*?"
                                                          + Pattern.quote(END));
    private static final Pattern REVISION = Pattern.compile("<" + REVISION_PROPERTY + ">[^<]*</"
                                                            + REVISION_PROPERTY + ">");
    private static final String LICENSE = """
        <?xml version="1.0" encoding="UTF-8"?>
        <!--
          ~ Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.
          ~
          ~ Licensed under the Apache License, Version 2.0 (the "License").
          ~ You may not use this file except in compliance with the License.
          ~ A copy of the License is located at
          ~
          ~  http://aws.amazon.com/apache2.0
          ~
          ~ or in the "license" file accompanying this file. This file is distributed
          ~ on an "AS IS" BASIS, WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either
          ~ express or implied. See the License for the specific language governing
          ~ permissions and limitations under the License.
          -->
        """;

    private ServiceFleetRenderer() {
    }

    /** The {@code pom.xml} of a service module whose services are {@code services} (its own service first). */
    public static String modulePom(List<FleetService> services) {
        FleetService first = services.get(0);
        StringBuilder pom = new StringBuilder(LICENSE);
        pom.append("<!--\n")
           .append("  ").append(GENERATED_MARKER).append("; do not edit.\n")
           .append("  The canonical model files under ").append(first.modelDirectory())
           .append(" are vendored verbatim from aws-models at the pinned\n")
           .append("  revision (aws.models.revision in ../pom.xml); aws-codegen:generate fails this module if their\n")
           .append("  digest differs from aws.codegen.modelDigest or a required V2 client type is not generated.\n")
           .append("-->\n");
        pom.append("""
            <project xmlns="http://maven.apache.org/POM/4.0.0"
                     xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
                     xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
                <modelVersion>4.0.0</modelVersion>
                <parent>
                    <groupId>software.amazon.awssdk</groupId>
                    <artifactId>v3-services</artifactId>
                    <version>3.0.0-SNAPSHOT</version>
                </parent>
            """);
        pom.append("    <artifactId>").append(first.module()).append("</artifactId>\n");
        pom.append("    <name>AWS Java SDK V3 :: Services :: ").append(first.sdkId()).append("</name>\n");
        pom.append("    <description>The AWS SDK for Java V3 client for ")
           .append(String.join(" and ", services.stream().map(FleetService::sdkId).toList()))
           .append(", generated from its canonical Smithy model.</description>\n");
        pom.append("    <properties>\n");
        property(pom, "aws.codegen.service", first.service());
        property(pom, "aws.codegen.packageName", first.packageName());
        if (!first.modelDirectory().equals(FleetService.PRIMARY_MODEL_DIRECTORY)) {
            property(pom, "aws.codegen.modelDirectory", "${project.basedir}/" + first.modelDirectory());
        }
        property(pom, "aws.codegen.modelDigest", first.modelDigest());
        property(pom, "aws.codegen.requiredTypes", String.join(",", first.requiredTypes()));
        pom.append("    </properties>\n");
        pom.append("    <dependencies>\n");
        services.stream().flatMap(s -> s.protocolModules().stream()).distinct().sorted().forEach(protocol -> {
            pom.append("        <dependency>\n")
               .append("            <groupId>software.amazon.awssdk</groupId>\n")
               .append("            <artifactId>").append(protocol).append("</artifactId>\n")
               .append("            <version>${project.version}</version>\n")
               .append("        </dependency>\n");
        });
        pom.append("    </dependencies>\n");
        if (services.size() > 1) {
            pom.append("    <build>\n        <plugins>\n            <plugin>\n")
               .append("                <groupId>software.amazon.awssdk</groupId>\n")
               .append("                <artifactId>aws-codegen-maven-plugin</artifactId>\n")
               .append("                <executions>\n");
            for (FleetService bundled : services.subList(1, services.size())) {
                String suffix = bundled.subPackage() == null ? bundled.module() : bundled.subPackage();
                pom.append("                    <!-- ").append(bundled.sdkId())
                   .append(", which the V2 module bundles in its ").append(bundled.packageName())
                   .append(" package. -->\n")
                   .append("                    <execution>\n")
                   .append("                        <id>aws-codegen-generate-").append(suffix).append("</id>\n")
                   .append("                        <phase>generate-sources</phase>\n")
                   .append("                        <goals>\n")
                   .append("                            <goal>generate</goal>\n")
                   .append("                        </goals>\n")
                   .append("                        <configuration>\n");
                configuration(pom, "service", bundled.service());
                configuration(pom, "packageName", bundled.packageName());
                configuration(pom, "modelDirectory", "${project.basedir}/" + bundled.modelDirectory());
                configuration(pom, "outputDirectory",
                              "${project.build.directory}/generated-sources/aws-codegen-" + suffix);
                configuration(pom, "resourceOutputDirectory",
                              "${project.build.directory}/generated-resources/aws-codegen-" + suffix);
                configuration(pom, "modelDigest", bundled.modelDigest());
                configuration(pom, "requiredTypes", String.join(",", bundled.requiredTypes()));
                pom.append("                        </configuration>\n")
                   .append("                    </execution>\n");
            }
            pom.append("                </executions>\n            </plugin>\n        </plugins>\n    </build>\n");
        }
        pom.append("</project>\n");
        return pom.toString();
    }

    /** The generated module list of the services aggregator, indented by {@code indent}. */
    public static String aggregatorModules(FleetPlan plan, String indent) {
        StringBuilder block = new StringBuilder(indent).append(BEGIN).append('\n');
        for (String module : plan.modules().keySet()) {
            block.append(indent).append("<module>").append(module).append("</module>\n");
        }
        return block.append(indent).append(END).toString();
    }

    /** The generated service entries of the BOM, indented by {@code indent}. */
    public static String bomEntries(FleetPlan plan, String indent) {
        StringBuilder block = new StringBuilder(indent).append(BEGIN).append('\n');
        for (String module : plan.modules().keySet()) {
            block.append(indent).append("<dependency>\n")
                 .append(indent).append("    <groupId>software.amazon.awssdk</groupId>\n")
                 .append(indent).append("    <artifactId>").append(module).append("</artifactId>\n")
                 .append(indent).append("    <version>${project.version}</version>\n")
                 .append(indent).append("</dependency>\n");
        }
        return block.append(indent).append(END).toString();
    }

    /** {@code pom} with its generated region replaced by {@code rendering} applied to the region's indentation. */
    static String replaceRegion(String pom, String file, Function<String, String> rendering) {
        Matcher region = REGION.matcher(pom);
        if (!region.find()) {
            throw new IllegalStateException(file + " has no " + BEGIN + " ... " + END + " region");
        }
        String replaced = pom.substring(0, region.start()) + rendering.apply(region.group(1))
                          + pom.substring(region.end());
        if (REGION.matcher(replaced).results().count() != 1) {
            throw new IllegalStateException(file + " must have exactly one generated region");
        }
        return replaced;
    }

    /** {@code pom} with the {@value #REVISION_PROPERTY} property set to {@code revision}. */
    static String pinRevision(String pom, String file, String revision) {
        Matcher matcher = REVISION.matcher(pom);
        if (!matcher.find()) {
            throw new IllegalStateException(file + " declares no <" + REVISION_PROPERTY + "> property");
        }
        return matcher.replaceFirst(Matcher.quoteReplacement("<" + REVISION_PROPERTY + ">" + revision + "</"
                                                             + REVISION_PROPERTY + ">"));
    }

    /** The {@value #REVISION_PROPERTY} value of {@code pom}, or {@code null}. */
    static String revision(String pom) {
        Matcher matcher = REVISION.matcher(pom);
        return matcher.find() ? matcher.group().replaceAll("</?" + Pattern.quote(REVISION_PROPERTY) + ">", "")
                              : null;
    }

    private static void property(StringBuilder pom, String name, String value) {
        pom.append("        <").append(name).append('>').append(value).append("</").append(name).append(">\n");
    }

    private static void configuration(StringBuilder pom, String name, String value) {
        pom.append("                            <").append(name).append('>').append(value).append("</")
           .append(name).append(">\n");
    }
}
