import software.amazon.awssdk.tools.paritymanifest.compat.CompatibilityFixturesCli;

/**
 * The compatibility fixtures that {@code test/codegen-generated-classes-test} executes against the generated V3
 * classes ({@code compatibility-fixtures.json}) are exactly what the generator produces from the Parity Manifest of
 * the released V2 API jars ({@code target/v2-api}, classified by the checked-in rules) for that module's test scope
 * ({@code compatibility-scope.txt}). That module is built without this tool (the foundation gate excludes release
 * tooling), so the fixtures are checked in and this test keeps them current.
 *
 * <p>It also keeps {@code compatibility-evidence-hooks.txt} current: the launch gate's evidence hooks those fixtures
 * provide (each entry bound to the suites that execute its fixtures).
 *
 * <p>To regenerate after changing the rules, the scope or the generator, run this test with
 * {@code -Dv3.compatibilityFixtures.update=true}.
 */
class CompatibilityFixturesGoldenTest {
    private static final Path MODULE = Path.of("../../test/codegen-generated-classes-test/src/test/resources");
    private static final Path SCOPE = MODULE.resolve("compatibility-scope.txt");
    private static final Path FIXTURES = MODULE.resolve("compatibility-fixtures.json");
    /** The evidence hooks the fixtures provide to the launch gate ({@link LaunchGateRepositoryTest}). */
    static final Path HOOKS = MODULE.resolve("compatibility-evidence-hooks.txt");
    /** The codegen-generated-classes-test suite that executes each fixture kind. */
    static final Map<CompatibilityFixture.Kind, String> SUITES = Map.of(
        CompatibilityFixture.Kind.COMPILE, "ManifestDiagnosticsTest",
        CompatibilityFixture.Kind.COMPILE_REJECTED, "ManifestDiagnosticsTest",
        CompatibilityFixture.Kind.LINK, "V2BytecodeOnV3Test",
        CompatibilityFixture.Kind.LINK_REJECTED, "V2BytecodeOnV3Test",
        CompatibilityFixture.Kind.SIGNATURE, "ApiShapeCompatibilityTest",
        CompatibilityFixture.Kind.HIERARCHY, "ApiShapeCompatibilityTest",
        CompatibilityFixture.Kind.BEHAVIOR, "BehaviorCompatibilityTest");
    private static final String HOOKS_HEADER =
        "# The launch-gate evidence hooks of compatibility-fixtures.json (task 13.3), in the EvidenceHooks text form:\n"
        + "# \"<suite> <entryId>\" for every entry each executing suite has a fixture for. Generated by\n"
        + "# CompatibilityFixturesGoldenTest in tools/parity-manifest; regenerate with\n"
        + "# -Dv3.compatibilityFixtures.update=true.\n";

    @TempDir
    Path temp;

    @Test
    void checkedInFixturesAreTheGeneratorOutputForTheTestScope() throws Exception {
        List<Path> jars = v2ApiJars();
        ParityManifest manifest = baselineManifest(jars);
        List<Path> baselineClassPath = new ArrayList<>(jars);
        baselineClassPath.addAll(v2ApiDependencies());
        CompatibilityFixtures fixtures = new CompatibilityFixtureGenerator(manifest,
                                                                           BaselineClasses.read(baselineClassPath))
            .generate(scope());
        String generated = fixtures.toJson();
        if (Boolean.getBoolean("v3.compatibilityFixtures.update")) {
            fixtures.write(FIXTURES);
        }
        assertTrue(Files.isRegularFile(FIXTURES), FIXTURES.toAbsolutePath() + " is missing; run with "
                                                  + "-Dv3.compatibilityFixtures.update=true");
        assertEquals(generated, Files.readString(FIXTURES, StandardCharsets.UTF_8),
                     "compatibility-fixtures.json is stale; regenerate with -Dv3.compatibilityFixtures.update=true");

        // The launch gate's evidence hooks for these fixtures: each entry is verified by the suites executing its
        // fixtures (task 13.3).
        String hooks = HOOKS_HEADER + fixtures.evidenceHooks(SUITES);
        EvidenceHooks.parse(hooks, HOOKS.toString());
        if (Boolean.getBoolean("v3.compatibilityFixtures.update")) {
            Files.writeString(HOOKS, hooks, StandardCharsets.UTF_8);
        }
        assertTrue(Files.isRegularFile(HOOKS), HOOKS.toAbsolutePath() + " is missing; run with "
                                               + "-Dv3.compatibilityFixtures.update=true");
        assertEquals(hooks, Files.readString(HOOKS, StandardCharsets.UTF_8),
                     "compatibility-evidence-hooks.txt is stale; regenerate with "
                     + "-Dv3.compatibilityFixtures.update=true");

        // Every caller is valid V2 code, so a rejected caller fails against V3 because of V3, not the generator.
        String classPath = baselineClassPath.stream().map(Path::toString)
                                            .collect(Collectors.joining(File.pathSeparator));
        List<String> invalid = new ArrayList<>();
        int index = 0;
        for (CompatibilityFixture f : fixtures.fixtures()) {
            if (f.source() != null) {
                List<String> errors = compile(f.source(), classPath, temp.resolve(Integer.toString(index++)));
                if (!errors.isEmpty()) {
                    invalid.add(f.id() + ": " + errors);
                }
            }
        }
        assertEquals(List.of(), invalid, "generated callers that do not compile against the V2 API jars");
    }

    /** The released V2 API jars of the fixture baseline ({@code target/v2-api}), sorted. */
    static List<Path> v2ApiJars() throws IOException {
        String version = System.getProperty("v3.fixture.v2Version");
        Path v2Api = Path.of(System.getProperty("v3.fixture.v2Api"));
        List<Path> jars;
        try (Stream<Path> files = Files.list(v2Api)) {
            jars = files.filter(p -> p.toString().endsWith("-" + version + ".jar")).sorted().toList();
        }
        assertFalse(jars.isEmpty(), "no V2 " + version + " API jars in " + v2Api);
        return jars;
    }

    /** The third-party jars the V2 API types extend ({@code target/v2-api-dependencies}); not scanned. */
    static List<Path> v2ApiDependencies() throws IOException {
        try (Stream<Path> files = Files.list(Path.of(System.getProperty("v3.fixture.v2ApiDependencies")))) {
            return files.filter(p -> p.toString().endsWith(".jar")).sorted().toList();
        }
    }

    /** The test scope of the checked-in fixtures ({@code compatibility-scope.txt}). */
    static List<String> scope() throws IOException {
        assertTrue(Files.isRegularFile(SCOPE), SCOPE.toAbsolutePath() + " moved; update this test");
        return CompatibilityFixturesCli.parseScope(Files.readString(SCOPE, StandardCharsets.UTF_8));
    }

    /** The checked-in compatibility fixtures, as JSON. */
    static String checkedInFixtures() throws IOException {
        return Files.readString(FIXTURES, StandardCharsets.UTF_8);
    }

    /**
     * The Parity Manifest of {@code jars} (the V2 API jars of {@link #v2ApiJars()}) under the checked-in
     * classification rules; valid, or the test fails.
     */
    static ParityManifest baselineManifest(List<Path> jars) throws Exception {
        return baselineManifest(jars, List.of());
    }

    /** {@link #baselineManifest(List)} with {@code extra} inventory items (for example artifacts and behaviors). */
    static ParityManifest baselineManifest(List<Path> jars, List<InventoryItem> extra) throws Exception {
        String version = System.getProperty("v3.fixture.v2Version");
        Map<String, InventoryItem> items = new TreeMap<>();
        extra.forEach(item -> items.putIfAbsent(item.id(), item));
        for (Path jar : jars) {
            String file = jar.getFileName().toString();
            String artifact = file.substring(0, file.length() - ("-" + version + ".jar").length());
            for (InventoryItem item : PublicApiInventorySource.scanJar(jar, artifact, artifact + "/" + file)) {
                items.putIfAbsent(item.id(), item);
            }
        }
        ClassificationRules.Classified classified =
            ClassificationRules.loadDefault().classify(List.copyOf(items.values()));
        assertEquals(List.of(), classified.problems());
        ParityManifest manifest = new ParityManifest(
            new BaselineIdentity(version, null, null, null, "parity-manifest/compatibility-fixtures"), null,
            classified.entries());
        assertEquals(List.of(), ManifestValidator.validate(manifest, ManifestValidator.Options.DEFAULT));
        return manifest;
    }

    private static List<String> compile(String source, String classPath, Path directory) throws Exception {
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        Path file = directory.resolve("src").resolve(CompatibilityFixture.CALLER_CLASS + ".java");
        Files.createDirectories(file.getParent());
        Files.writeString(file, source, StandardCharsets.UTF_8);
        Path classes = Files.createDirectories(directory.resolve("classes"));
        DiagnosticCollector<JavaFileObject> diagnostics = new DiagnosticCollector<>();
        try (StandardJavaFileManager manager = javac.getStandardFileManager(diagnostics, Locale.ROOT,
                                                                            StandardCharsets.UTF_8)) {
            javac.getTask(null, manager, diagnostics, List.of("-proc:none", "--release", "21", "-classpath", classPath,
                                                              "-d", classes.toString()),
                          null, manager.getJavaFileObjectsFromPaths(List.of(file))).call();
        }
        return diagnostics.getDiagnostics().stream().filter(d -> d.getKind() == Diagnostic.Kind.ERROR)
                          .map(d -> d.getMessage(Locale.ROOT)).toList();
    }
}
