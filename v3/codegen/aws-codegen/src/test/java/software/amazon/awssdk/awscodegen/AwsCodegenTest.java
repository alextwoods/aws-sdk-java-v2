    private static final String SERVICE = "example.weather#Weather";
    private static final String PACKAGE = "software.amazon.awssdk.services.weather";
    private static final Path INFO_FILE = Path.of("software/amazon/awssdk/services/weather/GeneratedServiceInfo.java");
    private static final Path OPERATION_FILES = Path.of("software/amazon/awssdk/services/weather/internal/operation");
    /**
     * Every file generated for the test model: the identity type, the service metadata, one descriptor, the
     * operation table, the model types with the service exception, the schemas and the type registry.
     */
    private static final Path SCHEMAS_FILE = Path.of("software/amazon/awssdk/services/weather/model/internal/"
                                                     + "WeatherSchemas.java");
    private static final Path MODEL_FILES = Path.of("software/amazon/awssdk/services/weather/model");
    private static final List<Path> GENERATED_FILES = List.of(
        INFO_FILE,
        Path.of("software/amazon/awssdk/services/weather/WeatherServiceMetadata.java"),
        OPERATION_FILES.resolve("GetForecastOperation.java"),
        OPERATION_FILES.resolve("WeatherOperations.java"),
        MODEL_FILES.resolve("GetForecastRequest.java"),
        MODEL_FILES.resolve("GetForecastResponse.java"),
        MODEL_FILES.resolve("WeatherException.java"),
        SCHEMAS_FILE,
        MODEL_FILES.resolve("internal/WeatherTypeRegistry.java"));

    @TempDir
    Path temp;

    @Test
    void generatesServiceInfoIntoServicePackage() throws IOException {
        Path models = writeModels(temp.resolve("a/model"));
        Path output = temp.resolve("a/generated");

        AwsCodegenResult result = AwsCodegen.generate(new AwsCodegenRequest(SERVICE, PACKAGE, models, output));

        assertEquals(GENERATED_FILES, ClientSources.withoutClients(result.generatedFiles()));
        assertEquals(output, result.sourceRoot());
        assertTrue(result.modelDigest().matches("sha256:[0-9a-f]{64}"), result.modelDigest());
        assertEquals(String.join("\n",
                                 "/*",
                                 " * Generated by software.amazon.awssdk:aws-codegen. Do not edit.",
                                 " */",
                                 "",
                                 "package " + PACKAGE + ";",
                                 "",
                                 "import software.amazon.awssdk.awscore.metadata.ModelProvenance;",
                                 "",
                                 "/**",
                                 " * Generation identity of the {@code " + SERVICE + "} service.",
                                 " */",
                                 "final class GeneratedServiceInfo {",
                                 "    /** Absolute Smithy shape ID of the generated service. */",
                                 "    static final String SERVICE_SHAPE_ID = \"" + SERVICE + "\";",
                                 "",
                                 "    /** Location-independent SHA-256 digest of the canonical model inputs. */",
                                 "    static final String MODEL_DIGEST = \"" + result.modelDigest() + "\";",
                                 "",
                                 "    /** Exact, untruncated immutable revision of the canonical model source. */",
                                 "    static final String MODEL_REVISION = \"" + result.modelDigest() + "\";",
                                 "",
                                 "    private GeneratedServiceInfo() {",
                                 "    }",
                                 "",
                                 "    /** The model provenance published in this service's artifact. */",
                                 "    static ModelProvenance provenance() {",
                                 "        return ModelProvenance.load(GeneratedServiceInfo.class, SERVICE_SHAPE_ID, "
                                 + "MODEL_REVISION);",
                                 "    }",
                                 "}",
                                 ""),
                     Files.readString(output.resolve(INFO_FILE)));
        // Unpinned requests publish their resources to the sibling <output>-resources directory.
        assertEquals(temp.resolve("a/generated-resources"), result.resourceRoot());
        assertOnlyOutputRemains(temp.resolve("a"), "generated", "generated-resources", "model");
    }

    @Test
    void outputIsByteIdenticalAcrossCheckoutLocations() throws IOException {
        Path outputA = temp.resolve("a/generated");
        Path outputB = temp.resolve("somewhere/else/entirely/generated");
        AwsCodegenResult a = AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, writeModels(temp.resolve("a/model")), outputA));
        AwsCodegenResult b = AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, writeModels(temp.resolve("somewhere/else/entirely/model")), outputB));

        assertEquals(a.modelDigest(), b.modelDigest());
        assertEquals(GENERATED_FILES, ClientSources.withoutClients(a.generatedFiles()));
        assertEquals(a.generatedFiles(), b.generatedFiles());
        for (Path file : a.generatedFiles()) {
            assertArrayEquals(Files.readAllBytes(outputA.resolve(file)), Files.readAllBytes(outputB.resolve(file)));
            String source = Files.readString(outputA.resolve(file));
            assertFalse(source.contains(temp.toString()), "generated sources must not contain absolute paths");
        }
    }

    @Test
    void digestChangesWhenModelContentChanges() throws IOException {
        Path models = writeModels(temp.resolve("model"));
        String before = AwsCodegen.digest(models, AwsCodegen.discoverModelFiles(models));
        Files.writeString(models.resolve("nested/operations.smithy"), "namespace example.weather\n// changed\n");
        String after = AwsCodegen.digest(models, AwsCodegen.discoverModelFiles(models));
        assertNotEquals(before, after);
    }

    @Test
    void regenerationRemovesStaleFiles() throws IOException {
        Path output = temp.resolve("generated");
        Files.createDirectories(output.resolve("stale"));
        Files.writeString(output.resolve("stale/Old.java"), "class Old {}");

        AwsCodegen.generate(new AwsCodegenRequest(SERVICE, PACKAGE, writeModels(temp.resolve("model")), output));

        assertFalse(Files.exists(output.resolve("stale/Old.java")));
        assertTrue(Files.exists(output.resolve(INFO_FILE)));
        assertOnlyOutputRemains(temp, "generated", "generated-resources", "model");
    }

    @Test
    void missingModelsFailWithoutTouchingPublishedTree() throws IOException {
        Path output = existingOutput();
        Path emptyModels = Files.createDirectories(temp.resolve("model"));

        AwsCodegenException e = assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, emptyModels, output)));
        assertTrue(e.getMessage().contains("No Smithy model files"), e.getMessage());
        assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, temp.resolve("absent"), output)));
        assertExistingOutputUntouched(output);
    }

    @Test
    void invalidModelsFailWithTheValidationEventsAndPublishNothing() throws IOException {
        Path output = existingOutput();
        Path models = writeModels(temp.resolve("model"));
        Files.writeString(models.resolve("broken.smithy"),
                          "$version: \"2\"\nnamespace example.weather\nstructure Broken { member: DoesNotExist }\n");

        AwsCodegenException e = assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, models, output)));
        assertTrue(e.getMessage().contains("is invalid"), e.getMessage());
        assertTrue(e.getMessage().contains("example.weather#DoesNotExist"), e.getMessage());
        assertExistingOutputUntouched(output);
    }

    @Test
    void serviceMissingFromTheModelFailsAndListsTheModeledServices() throws IOException {
        Path output = existingOutput();
        Path models = writeModels(temp.resolve("model"));

        AwsCodegenException e = assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest("example.weather#Other", PACKAGE, models, output)));
        assertTrue(e.getMessage().contains("example.weather#Other is not a service shape"), e.getMessage());
        assertTrue(e.getMessage().contains("[" + SERVICE + "]"), e.getMessage());
        assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest("example.weather#GetForecast", PACKAGE, models, output)));
        assertExistingOutputUntouched(output);
    }

    @Test
    void integrationsRunInOrderAndIdentifierOrderOverTheDirectedContext() throws IOException {
        Path models = writeModels(temp.resolve("model"));
        Path output = temp.resolve("generated");
        List<String> log = new ArrayList<>();
        List<AwsCodegenContext> contexts = new ArrayList<>();
        Consumer<AwsCodegenContext> capture = contexts::add;

        AwsCodegen.generate(new AwsCodegenRequest(SERVICE, PACKAGE, models, output),
                            List.of(new Recording("aws.zeta", 0, log, null),
                                    new Recording("aws.late", 10, log, null),
                                    new Recording("aws.alpha", 0, log, capture),
                                    new Recording("aws.early", -5, log, null)));

        assertEquals(List.of("aws.early:preprocess", "aws.alpha:preprocess", "aws.zeta:preprocess",
                             "aws.late:preprocess",
                             "aws.early:customize", "aws.alpha:customize", "aws.zeta:customize",
                             "aws.late:customize"),
                     log);
        AwsCodegenContext context = contexts.get(0);
        assertEquals(List.of("aws.early", "aws.alpha", "aws.zeta", "aws.late"),
                     context.integrations().stream().map(AwsCodegenIntegration::identifier).toList());
        assertEquals(ShapeId.from(SERVICE), context.service().getId());
        assertSame(context.service(), context.model().expectShape(ShapeId.from(SERVICE)));
        assertTrue(context.model().getShape(ShapeId.from("example.weather#GetForecast")).isPresent());
        assertEquals(new AwsCodegenSettings(ShapeId.from(SERVICE), PACKAGE), context.settings());
        assertEquals(output.toAbsolutePath().normalize(), context.fileManifest().getBaseDir());
        assertEquals(PACKAGE + ".GeneratedServiceInfo",
                     context.symbolProvider().toSymbol(context.service()).getFullName());
        assertTrue(context.modelDigest().startsWith("sha256:"));
    }

    @Test
    void integrationOutputIsStagedAndPublishedWithTheGeneratedTree() throws IOException {
        Path output = temp.resolve("generated");
        List<String> log = new ArrayList<>();
        Consumer<AwsCodegenContext> writeFiles = context -> {
            context.writerDelegator().useFileWriter("software/amazon/awssdk/services/weather/Extra.java", PACKAGE,
                                                    writer -> writer.write("final class Extra {"));
            context.fileManifest().writeFile("META-INF/aws-sdk-java-v3/extra.txt", "extra\n");
            assertFalse(Files.exists(output), "nothing is written to the output directory before publication");
        };

        AwsCodegenResult result = AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, writeModels(temp.resolve("model")), output),
            List.of(new Recording("aws.extra", 0, log, writeFiles)));

        List<Path> files = ClientSources.withoutClients(result.generatedFiles());
        assertEquals(List.of(Path.of("META-INF/aws-sdk-java-v3/extra.txt"),
                             Path.of("software/amazon/awssdk/services/weather/Extra.java")),
                     files.subList(0, 2));
        assertEquals(GENERATED_FILES, files.subList(2, files.size()));
        assertEquals("extra\n", Files.readString(output.resolve("META-INF/aws-sdk-java-v3/extra.txt")));
        assertTrue(Files.readString(output.resolve("software/amazon/awssdk/services/weather/Extra.java"))
                        .endsWith("package " + PACKAGE + ";\n\nfinal class Extra {\n"));
    }

    @Test
    void failingIntegrationFailsGenerationAndPublishesNothing() throws IOException {
        Path output = existingOutput();
        Consumer<AwsCodegenContext> fail = context -> {
            context.fileManifest().writeFile("partial.txt", "partial");
            throw new IllegalStateException("integration exploded");
        };

        AwsCodegenException e = assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, writeModels(temp.resolve("model")), output),
            List.of(new Recording("aws.failing", 0, new ArrayList<>(), fail))));

        assertTrue(e.getMessage().contains(SERVICE) && e.getMessage().contains("integration exploded"), e.getMessage());
        assertExistingOutputUntouched(output);
        assertOnlyOutputRemains(temp, "generated", "model");
    }

    @Test
    void writingOneFileTwiceFailsGeneration() throws IOException {
        Path output = existingOutput();
        Consumer<AwsCodegenContext> overwrite = context -> context.fileManifest().writeFile(INFO_FILE, "overwritten");

        AwsCodegenException e = assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, writeModels(temp.resolve("model")), output),
            List.of(new Recording("aws.overwrite", 0, new ArrayList<>(), overwrite))));

        // The integration overwrote a file the core generator owns: both contributors and the shape are reported.
        assertEquals(1, e.diagnostics().size(), e.getMessage());
        Diagnostic conflict = e.diagnostics().get(0);
        assertEquals(DiagnosticCode.INTEGRATION_OUTPUT_CONFLICT, conflict.code());
        assertEquals(List.of(AwsCodegen.GENERATOR_IDENTIFIER, "aws.overwrite"), conflict.integrations());
        assertEquals(Optional.of(SERVICE), conflict.shape());
        assertEquals("output " + StagedFileManifest.portable(INFO_FILE), conflict.element());
        assertExistingOutputUntouched(output);
    }

    @Test
    void invalidIntegrationsFailBeforeTheModelIsProcessed() throws IOException {
        Path output = existingOutput();
        List<String> log = new ArrayList<>();

        AwsCodegenException e = assertThrows(AwsCodegenException.class, () -> AwsCodegen.generate(
            new AwsCodegenRequest(SERVICE, PACKAGE, writeModels(temp.resolve("model")), output),
            List.of(new Recording("aws.same", 0, log, null), new Recording("aws.same", 1, log, null))));

        assertTrue(e.getMessage().contains("share identifier 'aws.same'"), e.getMessage());
        assertEquals(List.of(), log);
        assertExistingOutputUntouched(output);
    }

    @Test
    void rejectsInvalidServiceShapeIdsAndPackages() {
        Path dir = temp.resolve("x");
        assertThrows(AwsCodegenException.class, () -> new AwsCodegenRequest("Weather", PACKAGE, dir, dir));
        assertThrows(AwsCodegenException.class, () -> new AwsCodegenRequest("example#", PACKAGE, dir, dir));
        assertThrows(AwsCodegenException.class, () -> new AwsCodegenRequest("a\"b#C", PACKAGE, dir, dir));
        assertThrows(AwsCodegenException.class, () -> new AwsCodegenRequest(SERVICE, "Software.Amazon", dir, dir));
        assertThrows(AwsCodegenException.class, () -> new AwsCodegenRequest(SERVICE, "a..b", dir, dir));
        assertThrows(AwsCodegenException.class, () -> new AwsCodegenRequest(SERVICE, "a.class.b", dir, dir));
        assertThrows(AwsCodegenException.class,
                     () -> new AwsCodegenSettings(ShapeId.from("example.weather#Weather$member"), PACKAGE));
    }

    /** Records hook invocations; optionally runs {@code onCustomize} with the context. */
    private record Recording(String identifier, int order, List<String> log, Consumer<AwsCodegenContext> onCustomize)
        implements AwsCodegenIntegration {

        @Override
        public Model preprocessModel(Model model, AwsCodegenSettings settings) {
            log.add(identifier + ":preprocess");
            return model;
        }

        @Override
        public void customize(AwsCodegenContext context) {
            log.add(identifier + ":customize");
            if (onCustomize != null) {
                onCustomize.accept(context);
            }
        }
    }

    private Path existingOutput() throws IOException {
        Path output = Files.createDirectories(temp.resolve("generated"));
        Files.writeString(output.resolve("Existing.java"), "class Existing {}");
        return output;
    }

    private static void assertExistingOutputUntouched(Path output) throws IOException {
        try (Stream<Path> files = Files.walk(output)) {
            assertEquals(List.of(output.resolve("Existing.java")), files.filter(Files::isRegularFile).toList());
        }
        assertEquals("class Existing {}", Files.readString(output.resolve("Existing.java")));
    }

    /** No staging or previous-tree directories remain next to the output. */
    private static void assertOnlyOutputRemains(Path parent, String... names) throws IOException {
        try (Stream<Path> children = Files.list(parent)) {
            assertEquals(List.of(names), children.map(p -> p.getFileName().toString()).sorted().toList());
        }
    }

    private static Path writeModels(Path directory) throws IOException {
        Files.createDirectories(directory.resolve("nested"));
        Files.writeString(directory.resolve("weather.smithy"),
                          "$version: \"2\"\nnamespace example.weather\n"
                          + "@aws.protocols#awsJson1_0\n@aws.auth#sigv4(name: \"weather\")\n"
                          + "service Weather { version: \"2006-03-01\", operations: [GetForecast] }\n",
                          StandardCharsets.UTF_8);
        Files.writeString(directory.resolve("nested/operations.smithy"),
                          "$version: \"2\"\nnamespace example.weather\n"
                          + "operation GetForecast {\n    input := { city: String }\n    output := { summary: String }\n}\n",
                          StandardCharsets.UTF_8);
        Files.writeString(directory.resolve("README.txt"), "not a model", StandardCharsets.UTF_8);
        return directory;
    }
