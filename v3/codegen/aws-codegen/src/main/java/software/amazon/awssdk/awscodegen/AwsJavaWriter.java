package software.amazon.awssdk.awscodegen;

import java.util.Collection;
import java.util.Map;
import java.util.Optional;
import java.util.SequencedCollection;
import java.util.SequencedMap;
import java.util.Set;
import software.amazon.smithy.codegen.core.CodegenException;
import software.amazon.smithy.codegen.core.Symbol;
import software.amazon.smithy.codegen.core.SymbolWriter;
import software.amazon.smithy.utils.AbstractCodeWriter;
import software.amazon.smithy.utils.StringUtils;

/**
 * Writer for one generated Java source file, created by {@link AwsCodegenContext#writerDelegator()}.
 *
 * <p>Types are referenced with {@code $T} and a {@link Symbol}; the writer records the import and writes the shortest
 * unambiguous name (see {@link JavaImports}). Templates should reference every type through {@code $T}, including
 * {@code java.lang} types, so that a generated type that shadows a {@code java.lang} name is handled correctly.
 *
 * <p>{@link #toString()} renders the generated-file header, the package declaration and the sorted imports ahead of
 * the body, with {@code \n} line separators. It writes no timestamps, absolute paths or other environment-dependent
 * content.
 *
 * <p>Output must not depend on hash iteration order (Requirement 3.6): {@code $L} and {@code $S} reject a
 * {@link Collection} or {@link Map} argument without a defined encounter order (for example a {@code HashSet},
 * {@code HashMap}, {@code Set.of(...)} or {@code Map.of(...)}, whose order can change between JVM runs). Pass a
 * {@code List}, a sorted collection or map, or render entries from {@link CodegenOrdering} instead.
 */
public final class AwsJavaWriter extends SymbolWriter<AwsJavaWriter, JavaImports> {

    /** First comment line of every generated Java file. */
    public static final String GENERATED_HEADER = "Generated by software.amazon.awssdk:aws-codegen. Do not edit.";

    private final String packageName;
    private final Runnable onUse;

    AwsJavaWriter(String filename, String packageName) {
        this(filename, packageName, () -> {
        });
    }

    /**
     * @param onUse run when the writer is created and on every later write, so the contributor using it is attributed
     *        (a reused writer is always written to first, with the delegator's automatic separator)
     */
    AwsJavaWriter(String filename, String packageName, Runnable onUse) {
        this(filename, packageName, onUse, Set.of());
    }

    /**
     * @param packageTypeNames simple names of the types generated into {@code packageName}, which shadow
     *        {@code java.lang} types of the same name (see {@link JavaImports})
     */
    AwsJavaWriter(String filename, String packageName, Runnable onUse, Set<String> packageTypeNames) {
        super(new JavaImports(packageName, packageTypeNames));
        if (!filename.endsWith(".java")) {
            throw new CodegenException("AwsJavaWriter only writes Java sources, not " + filename
                                       + "; write resources through the context's FileManifest.");
        }
        this.packageName = packageName;
        this.onUse = onUse;
        trimTrailingSpaces(true);
        setNewline('\n');
        putFormatter('T', this::formatType);
        putFormatter('L', (value, indent) -> AbstractCodeWriter.formatLiteral(requireOrdered(value)));
        putFormatter('S', (value, indent) -> StringUtils.escapeJavaString(
            AbstractCodeWriter.formatLiteral(requireOrdered(value)), indent));
        onUse.run();
    }

    @Override
    public AwsJavaWriter write(Object content, Object... args) {
        onUse.run();
        return super.write(content, args);
    }

    @Override
    public AwsJavaWriter writeInline(Object content, Object... args) {
        onUse.run();
        return super.writeInline(content, args);
    }

    /** Rejects collections and maps whose iteration order is not defined; see the class documentation. */
    static Object requireOrdered(Object value) {
        Object inner = value instanceof Optional<?> optional ? optional.orElse(null) : value;
        if ((inner instanceof Collection<?> && !(inner instanceof SequencedCollection<?>))
            || (inner instanceof Map<?, ?> && !(inner instanceof SequencedMap<?, ?>))) {
            throw new CodegenException("Generated output must not depend on hash iteration order: pass a List, a "
                                       + "sorted collection or a sorted map instead of " + inner.getClass().getName());
        }
        return value;
    }

    /**
     * Claims the simple names of the file's own type {@code type} and of its nested types {@code nested}, which
     * templates write by simple name, so that no imported symbol can shadow them; call it before writing anything.
     */
    public AwsJavaWriter reserveTypeNames(Symbol type, String... nested) {
        getImportContainer().reserve(type.getName(), type.getFullName());
        for (String name : nested) {
            getImportContainer().reserve(name, type.getFullName() + "." + name);
        }
        return this;
    }

    private String formatType(Object value, String indent) {
        if (!(value instanceof Symbol symbol)) {
            throw new CodegenException("$T expects a Symbol but found " + value);
        }
        addImport(symbol, symbol.getName());
        return getImportContainer().reference(symbol);
    }

    @Override
    public String toString() {
        String body = super.toString();
        StringBuilder file = new StringBuilder("/*\n * ").append(GENERATED_HEADER).append("\n */\n\n");
        if (!packageName.isEmpty()) {
            file.append("package ").append(packageName).append(";\n\n");
        }
        String imports = getImportContainer().toString();
        if (!imports.isEmpty()) {
            file.append(imports).append('\n');
        }
        return file.append(body).toString();
    }
}
