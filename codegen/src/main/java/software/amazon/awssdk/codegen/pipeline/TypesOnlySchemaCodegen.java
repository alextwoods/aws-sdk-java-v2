package software.amazon.awssdk.codegen.pipeline;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Objects;
import java.util.stream.Collectors;
import software.amazon.awssdk.annotations.SdkInternalApi;
import software.amazon.awssdk.codegen.emitters.PoetGeneratorTask;
import software.amazon.awssdk.codegen.emitters.tasks.SchemaGeneratorTasks;
import software.amazon.awssdk.codegen.internal.Utils;
import software.amazon.awssdk.codegen.model.intermediate.IntermediateModel;
import software.amazon.awssdk.codegen.poet.ClassSpec;
import software.amazon.awssdk.codegen.poet.schema.SchemaCodegen;
import software.amazon.awssdk.codegen.schema.TraitInclusionConfig;
import software.amazon.awssdk.codegen.schema.TraitInclusionPolicy;
import software.amazon.awssdk.codegen.schema.TraitInitializers;
import software.amazon.smithy.model.Model;
import software.amazon.smithy.model.loader.ModelAssembler;
import software.amazon.smithy.model.shapes.ServiceShape;
import software.amazon.smithy.model.shapes.Shape;
import software.amazon.smithy.model.shapes.ShapeId;
import software.amazon.smithy.model.validation.ValidatedResult;
import software.amazon.smithy.model.validation.ValidationEvent;

/**
 * Types-only code generation: generates the Schemas of a Smithy model ({@code <Prefix>Schemas}, …, and
 * {@code <Prefix>SchemaIndex} with its {@code META-INF/services} entry) and nothing else. No intermediate model, client,
 * model classes, operations or protocol classes are generated. Libraries whose model classes are hand-written and
 * implement {@code SerializableStruct} themselves use it, such as S3 Event Notifications (design D.7).
 *
 * <p>The model is assembled and validated as stage 4 of the {@link CodegenPipeline} assembles native Smithy files: any
 * {@code ERROR} or {@code DANGER} event fails. The schemas are generated by {@link SchemaCodegen} in types-only mode for
 * the closure of the service's operations and errors plus the root shapes. Every class is computed before a file is
 * written, so a failure writes nothing. The Maven plugin's {@code generate-types} goal calls this class.
 */
@SdkInternalApi
public final class TypesOnlySchemaCodegen {
    private final List<Path> smithyModelSources;
    private final ShapeId service;
    private final List<ShapeId> rootShapes;
    private final String packageName;
    private final String classPrefix;
    private final Path sourcesDirectory;
    private final Path resourcesDirectory;
    private final ClassLoader classLoader;

    private TypesOnlySchemaCodegen(Builder builder) {
        this.smithyModelSources = Collections.unmodifiableList(new ArrayList<>(
            Objects.requireNonNull(builder.smithyModelSources, "smithyModelSources")));
        if (smithyModelSources.isEmpty()) {
            throw new IllegalArgumentException("smithyModelSources must not be empty");
        }
        this.service = Objects.requireNonNull(builder.service, "service");
        this.rootShapes = Collections.unmodifiableList(new ArrayList<>(
            Objects.requireNonNull(builder.rootShapes, "rootShapes")));
        this.packageName = Objects.requireNonNull(builder.packageName, "packageName");
        this.classPrefix = Objects.requireNonNull(builder.classPrefix, "classPrefix");
        this.sourcesDirectory = Objects.requireNonNull(builder.sourcesDirectory, "sourcesDirectory");
        this.resourcesDirectory = Objects.requireNonNull(builder.resourcesDirectory, "resourcesDirectory");
        this.classLoader = builder.classLoader == null ? TypesOnlySchemaCodegen.class.getClassLoader()
                                                       : builder.classLoader;
    }

    public static Builder builder() {
        return new Builder();
    }

    /**
     * Assembles and validates the model and writes the generated classes and the service registration file.
     *
     * @return the prepared generator, whose {@link SchemaCodegen#classSpecs()} were written
     * @throws IllegalArgumentException if a model source does not exist, or the service is not a service shape of the
     *     model
     * @throws IllegalStateException if the model has validation events of severity {@code ERROR} or {@code DANGER}
     * @throws software.amazon.awssdk.codegen.schema.SchemaCodegenException if schema generation cannot proceed
     */
    public SchemaCodegen generate() {
        Model model = assemble();
        ServiceShape serviceShape = model.getShape(service).flatMap(Shape::asServiceShape)
                                         .orElseThrow(() -> new IllegalArgumentException(
                                             "The Smithy model has no service shape " + service));
        SchemaCodegen codegen = SchemaCodegen.builder()
                                             .typesOnly(true)
                                             .model(model)
                                             .service(serviceShape)
                                             .rootShapes(rootShapes)
                                             .policy(TraitInclusionPolicy.forService(model, serviceShape,
                                                                                     TraitInclusionConfig.empty()))
                                             .initializers(TraitInitializers.load(classLoader))
                                             .modelPackage(packageName)
                                             .serviceName(classPrefix)
                                             .build();
        Path packageDirectory = sourcesDirectory.resolve(Utils.packageToDirectory(packageName));
        for (ClassSpec spec : codegen.classSpecs()) {
            new PoetGeneratorTask(packageDirectory.toString(), IntermediateModel.defaultFileHeader(), spec).invoke();
        }
        SchemaGeneratorTasks.serviceFileTask(resourcesDirectory, codegen).invoke();
        return codegen;
    }

    private Model assemble() {
        ModelAssembler assembler = SmithyModelDiscovery.discoverModels(Model.assembler(classLoader), classLoader);
        for (Path source : smithyModelSources) {
            if (!Files.exists(source)) {
                throw new IllegalArgumentException("The Smithy model source " + source + " does not exist");
            }
            assembler.addImport(source);
        }
        ValidatedResult<Model> result = assembler.assemble();
        List<ValidationEvent> failures = result.getValidationEvents().stream()
                                               .filter(SmithyValidationSuppressions::isFailure)
                                               .collect(Collectors.toList());
        if (!failures.isEmpty()) {
            throw new IllegalStateException("The Smithy model of " + service + " has " + failures.size()
                                            + " validation event(s) of severity ERROR or DANGER:\n"
                                            + failures.stream().map(CodegenPipeline::describe)
                                                      .collect(Collectors.joining("\n")));
        }
        return result.unwrap();
    }

    /**
     * Inputs of a {@link TypesOnlySchemaCodegen}.
     */
    public static final class Builder {
        private List<Path> smithyModelSources;
        private ShapeId service;
        private List<ShapeId> rootShapes = Collections.emptyList();
        private String packageName;
        private String classPrefix;
        private Path sourcesDirectory;
        private Path resourcesDirectory;
        private ClassLoader classLoader;

        private Builder() {
        }

        /**
         * @param smithyModelSources Smithy model files or directories
         */
        public Builder smithyModelSources(List<Path> smithyModelSources) {
            this.smithyModelSources = smithyModelSources;
            return this;
        }

        /**
         * @param service the service shape whose namespace and closure the schemas use; it may have no operations
         */
        public Builder service(ShapeId service) {
            this.service = service;
            return this;
        }

        /**
         * @param rootShapes shapes that get schemas, with every shape they reach, in addition to the service closure
         */
        public Builder rootShapes(List<ShapeId> rootShapes) {
            this.rootShapes = rootShapes;
            return this;
        }

        /**
         * @param packageName the package of the generated classes
         */
        public Builder packageName(String packageName) {
            this.packageName = packageName;
            return this;
        }

        /**
         * @param classPrefix the class name prefix: {@code <Prefix>Schemas}, {@code <Prefix>SchemaIndex}
         */
        public Builder classPrefix(String classPrefix) {
            this.classPrefix = classPrefix;
            return this;
        }

        /**
         * @param sourcesDirectory the root of the generated Java sources
         */
        public Builder sourcesDirectory(Path sourcesDirectory) {
            this.sourcesDirectory = sourcesDirectory;
            return this;
        }

        /**
         * @param resourcesDirectory the root of the generated resources, which gets the {@code META-INF/services} entry
         */
        public Builder resourcesDirectory(Path resourcesDirectory) {
            this.resourcesDirectory = resourcesDirectory;
            return this;
        }

        /**
         * @param classLoader the class loader of the Smithy model discovery and the trait initializers; defaults to
         *     this class's
         */
        public Builder classLoader(ClassLoader classLoader) {
            this.classLoader = classLoader;
            return this;
        }

        public TypesOnlySchemaCodegen build() {
            return new TypesOnlySchemaCodegen(this);
        }
    }
}
