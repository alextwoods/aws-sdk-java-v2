package software.amazon.awssdk.codegen.poet.client.specs;

import com.squareup.javapoet.ClassName;
import com.squareup.javapoet.CodeBlock;
import com.squareup.javapoet.FieldSpec;
import com.squareup.javapoet.MethodSpec;
import com.squareup.javapoet.TypeName;
import java.util.Collection;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.CompletableFuture;
import software.amazon.awssdk.annotations.SdkInternalApi;
import software.amazon.awssdk.codegen.model.intermediate.IntermediateModel;
import software.amazon.awssdk.codegen.model.intermediate.OperationModel;
import software.amazon.awssdk.codegen.poet.PoetExtension;
import software.amazon.awssdk.codegen.poet.client.traits.HttpChecksumRequiredTrait;
import software.amazon.awssdk.codegen.poet.client.traits.HttpChecksumTrait;
import software.amazon.awssdk.codegen.poet.client.traits.LongPollTrait;
import software.amazon.awssdk.codegen.poet.client.traits.RequestCompressionTrait;
import software.amazon.awssdk.codegen.poet.schema.SchemaOperationRouting;
import software.amazon.awssdk.core.client.handler.ClientExecutionParams;
import software.amazon.awssdk.core.client.handler.SyncClientHandler;
import software.amazon.awssdk.utils.CompletableFutureUtils;

/**
 * The protocol spec of a client whose calls run on the schema-based pipeline path (task 3.32): for every operation that
 * {@link SchemaOperationRouting} routes, the client method passes the operation's {@code <Svc>Operations} constant to
 * {@code ClientExecutionParams.withOperation} and generates no marshaller, response handler or exception metadata
 * mapping; the client protocol in the configuration serializes the request and resolves errors through the operation's
 * Error_Registry. Every other {@code ClientExecutionParams} setting of the legacy call is kept (protocol metadata, host
 * prefix, discovered endpoint, credential type, long polling, request configuration, metric collector, auth scheme and
 * endpoint resolvers, checksum and compression attributes).
 *
 * <p>Operations that are not routed are generated by the legacy spec. The protocol factory field, its {@code init}
 * method and the client's error response handler factory are generated only when such an operation exists.
 */
@SdkInternalApi
public final class SchemaOperationsProtocolSpec implements ProtocolSpec {
    private final ProtocolSpec legacy;
    private final SchemaOperationRouting routing;
    private final IntermediateModel model;
    private final PoetExtension poetExtensions;
    private final boolean hasLegacyOperations;

    /**
     * @param legacy the protocol's legacy spec, which generates the operations that are not routed
     * @param routing the client's operation routing
     * @param model the intermediate model
     * @param poetExtensions the model's class names
     * @param clientOperations the operations the client class generates methods for (the sync client has no
     *     event-stream methods)
     */
    public SchemaOperationsProtocolSpec(ProtocolSpec legacy, SchemaOperationRouting routing, IntermediateModel model,
                                        PoetExtension poetExtensions, Collection<OperationModel> clientOperations) {
        this.legacy = legacy;
        this.routing = routing;
        this.model = model;
        this.poetExtensions = poetExtensions;
        this.hasLegacyOperations = routing.hasLegacyOperations(clientOperations);
    }

    @Override
    public boolean usesProtocolFactory() {
        return hasLegacyOperations;
    }

    @Override
    public FieldSpec protocolFactory(IntermediateModel intermediateModel) {
        return legacy.protocolFactory(intermediateModel);
    }

    @Override
    public MethodSpec initProtocolFactory(IntermediateModel intermediateModel) {
        return legacy.initProtocolFactory(intermediateModel);
    }

    @Override
    public CodeBlock responseHandler(IntermediateModel intermediateModel, OperationModel opModel) {
        return routing.routes(opModel) ? CodeBlock.builder().build() : legacy.responseHandler(intermediateModel, opModel);
    }

    @Override
    public Optional<CodeBlock> errorResponseHandler(OperationModel opModel) {
        return routing.routes(opModel) ? Optional.empty() : legacy.errorResponseHandler(opModel);
    }

    @Override
    public CodeBlock executionHandler(OperationModel opModel) {
        if (!routing.routes(opModel)) {
            return legacy.executionHandler(opModel);
        }
        return CodeBlock.builder()
                        .add("\n\nreturn clientHandler.execute(")
                        .add(executionParams(opModel))
                        .add(");")
                        .build();
    }

    @Override
    public CodeBlock asyncExecutionHandler(IntermediateModel intermediateModel, OperationModel opModel) {
        if (!routing.routes(opModel)) {
            return legacy.asyncExecutionHandler(intermediateModel, opModel);
        }
        TypeName responseType = getPojoResponseType(opModel, poetExtensions);
        boolean discovery = opModel.getEndpointDiscovery() != null;
        return CodeBlock.builder()
                        .add("\n\n$T<$T> executeFuture = ", CompletableFuture.class, responseType)
                        .add(discovery ? "endpointFuture.thenCompose(cachedEndpoint -> " : "")
                        .add("clientHandler.execute(")
                        .add(executionParams(opModel))
                        .add(")")
                        .add(discovery ? ");" : ";")
                        .addStatement("$T<$T> whenCompleted = executeFuture$L", CompletableFuture.class, responseType,
                                      publishMetricsWhenComplete())
                        .addStatement("executeFuture = $T.forwardExceptionTo(whenCompleted, executeFuture)",
                                      CompletableFutureUtils.class)
                        .addStatement("return executeFuture")
                        .build();
    }

    /**
     * The {@code ClientExecutionParams} of a routed call: the legacy call's settings with {@code withOperation} in place
     * of the operation name, marshaller and response handlers.
     */
    private CodeBlock executionParams(OperationModel opModel) {
        TypeName responseType = getPojoResponseType(opModel, poetExtensions);
        ClassName requestType = poetExtensions.getModelClass(opModel.getInput().getVariableType());
        CodeBlock.Builder params = CodeBlock.builder()
                                            .add("new $T<$T, $T>()\n", ClientExecutionParams.class, requestType,
                                                 responseType)
                                            .add(".withOperation($L)\n", routing.operationReference(opModel));
        if (routing.renamesOperation(opModel)) {
            params.add(".withOperationName($S)\n", opModel.getOperationName());
        }
        return params.add(".withProtocolMetadata(protocolMetadata)\n")
                     .add(hostPrefixExpression(opModel))
                     .add(discoveredEndpoint(opModel))
                     .add(credentialType(opModel, model))
                     .add(LongPollTrait.executionParamSetter(opModel))
                     .add(".withRequestConfiguration(clientConfiguration)\n")
                     .add(".withInput($L)\n", opModel.getInput().getVariableName())
                     .add(".withMetricCollector(apiCallMetricCollector)\n")
                     .add(".withAuthSchemeOptionsResolver(this::resolveAuthSchemeOptions)\n")
                     .add(".withEndpointResolver(this::resolveEndpoint)\n")
                     .add(HttpChecksumRequiredTrait.putHttpChecksumAttribute(opModel))
                     .add(HttpChecksumTrait.create(opModel))
                     .add(RequestCompressionTrait.create(opModel, model))
                     .build();
    }

    @Override
    public Class<? extends SyncClientHandler> getClientHandlerClass() {
        return legacy.getClientHandlerClass();
    }

    @Override
    public Optional<MethodSpec> createErrorResponseHandler() {
        return hasLegacyOperations ? legacy.createErrorResponseHandler() : Optional.empty();
    }

    @Override
    public Optional<MethodSpec> createEventstreamErrorResponseHandler() {
        return hasLegacyOperations ? legacy.createEventstreamErrorResponseHandler() : Optional.empty();
    }

    @Override
    public List<MethodSpec> additionalMethods() {
        return legacy.additionalMethods();
    }
}
