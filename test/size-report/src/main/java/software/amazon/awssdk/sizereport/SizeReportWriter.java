package software.amazon.awssdk.sizereport;

import java.util.ArrayList;
import java.util.EnumMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.TreeSet;
import software.amazon.awssdk.annotations.SdkInternalApi;

/**
 * Renders the Size_Report as Markdown ({@code docs/design/schema-serde/size-report.md}).
 */
@SdkInternalApi
final class SizeReportWriter {
    private static final String NL = "\n";
    private static final int LARGEST_CHANGES = 15;

    private final Properties buildInfo;
    private final String featureJavaVersion;
    private final String featureJavaVendor;
    private final ClassFileFingerprint baselineFingerprint;
    private final ClassFileFingerprint featureFingerprint;
    private final Map<String, List<String>> disabledCustomizations;
    private final List<ServiceComparison> services;
    private final ModuleComparison modules;
    private final StringBuilder out = new StringBuilder();

    SizeReportWriter(Properties buildInfo, String featureJavaVersion, String featureJavaVendor,
                     ClassFileFingerprint baselineFingerprint, ClassFileFingerprint featureFingerprint,
                     Map<String, List<String>> disabledCustomizations, List<ServiceComparison> services,
                     ModuleComparison modules) {
        this.buildInfo = buildInfo;
        this.featureJavaVersion = featureJavaVersion;
        this.featureJavaVendor = featureJavaVendor;
        this.baselineFingerprint = baselineFingerprint;
        this.featureFingerprint = featureFingerprint;
        this.disabledCustomizations = disabledCustomizations;
        this.services = services;
        this.modules = modules;
    }

    String render() {
        header();
        builds();
        summary();
        for (ServiceComparison service : services) {
            service(service);
        }
        modules();
        method();
        return out.toString();
    }

    private void header() {
        line("# Size_Report");
        line();
        line("<!-- Generated by test/size-report (SizeReportDocumentTest). Do not edit this file by hand. -->");
        line();
        line("Artifact sizes of the Baseline_Build and the feature build for the Prototype_Service_Set services "
             + "(Requirement 36). All sizes are in bytes. Task 9.27 adds the services and module rows not reported "
             + "yet.");
        line();
        line("`mvn clean install -pl :size-report` regenerates this report from the JARs and fails if this file "
             + "differs. To update it: build the Baseline_Build once with `" + SizeReport.BUILD_SCRIPT + "`, build "
             + "the services, then run `mvn clean install -pl :size-report -Dsize-report.update=true`. See "
             + "`test/size-report/README.md`.");
        line();
    }

    private void builds() {
        String commit = buildInfo.getProperty("baseline.commit", "");
        String shortCommit = commit.length() > 12 ? commit.substring(0, 12) : commit;
        line("## Builds (Requirement 36.7)");
        line();
        line("| | Baseline_Build | Feature build |");
        line("|---|---|---|");
        line("| Source | commit `" + shortCommit + "`, the merge base of this branch | this branch |");
        line("| JDK | " + buildInfo.getProperty("java.version") + " (" + buildInfo.getProperty("java.vendor") + ") | "
             + featureJavaVersion + " (" + featureJavaVendor + ") |");
        line("| Build | `mvn " + buildInfo.getProperty("maven.flags") + "` (Maven "
             + buildInfo.getProperty("maven.version") + ") in a worktree of the commit, by `"
             + SizeReport.BUILD_SCRIPT + "` | the reactor build of this checkout that installed the service JARs |");
        line("| Compiler options | `" + buildInfo.getProperty("compiler.options") + "` | the same: `"
             + SizeReport.BUILD_SCRIPT + "` compares the effective `maven-compiler-plugin` configuration of both "
             + "checkouts |");
        line("| Class files | " + baselineFingerprint.describe() + " | " + featureFingerprint.describe() + " |");
        line();
        line("Codegen customizations disabled in the feature build (from `disabled-customizations.md`):");
        line();
        line("| Service | Disabled customizations |");
        line("|---|---|");
        for (Map.Entry<String, List<String>> entry : disabledCustomizations.entrySet()) {
            String disabled = entry.getValue().isEmpty() ? "None" : String.join("; ", entry.getValue());
            line("| " + entry.getKey() + " | " + disabled + " |");
        }
        line();
    }

    private void summary() {
        line("## Summary (Requirements 36.1, 36.3, 36.8)");
        line();
        line("| Service | Compressed JAR | Change | Uncompressed class bytes | Change | `.class` entries | "
             + "Requirement 36.3 |");
        line("|---|---|---|---|---|---|---|");
        for (ServiceComparison s : services) {
            String verdict = s.meetsJarSizeRequirement()
                             ? "Meets"
                             : "**Fails**: the JAR grows; categories with a net increase: "
                               + labels(s.grownCategories());
            line("| " + s.displayName()
                 + " | " + n(s.baseline().compressedBytes()) + " → " + n(s.feature().compressedBytes())
                 + " | " + change(s.compressedChange(), s.baseline().compressedBytes())
                 + " | " + n(s.baseline().classBytes()) + " → " + n(s.feature().classBytes())
                 + " | " + change(s.classBytesChange(), s.baseline().classBytes())
                 + " | " + n(s.baseline().classCount()) + " → " + n(s.feature().classCount())
                 + " | " + verdict + " |");
        }
        line();
    }

    private void service(ServiceComparison s) {
        line("## " + s.displayName() + " (`" + s.artifactId() + "`)");
        line();
        line("Service packages: " + codeList(dotted(s.feature().servicePackages())) + ".");
        line();
        line("| Measure | Baseline_Build | Feature build | Change |");
        line("|---|---|---|---|");
        line("| Compressed main JAR | " + n(s.baseline().compressedBytes()) + " | " + n(s.feature().compressedBytes())
             + " | " + change(s.compressedChange(), s.baseline().compressedBytes()) + " |");
        line("| Uncompressed class-file bytes | " + n(s.baseline().classBytes()) + " | " + n(s.feature().classBytes())
             + " | " + change(s.classBytesChange(), s.baseline().classBytes()) + " |");
        line("| `.class` entries | " + n(s.baseline().classCount()) + " | " + n(s.feature().classCount()) + " | "
             + signed(s.feature().classCount() - s.baseline().classCount()) + " |");
        line();

        line("### Change by category (Requirement 36.2)");
        line();
        line("| Category | Baseline_Build | Feature build | Change |");
        line("|---|---|---|---|");
        for (SizeCategory category : SizeCategory.values()) {
            line("| " + category.label() + " | " + n(s.baseline().categoryBytes().get(category)) + " | "
                 + n(s.feature().categoryBytes().get(category)) + " | " + signed(s.categoryChanges().get(category))
                 + " |");
        }
        line("| **Total** | " + n(s.baseline().classBytes()) + " | " + n(s.feature().classBytes()) + " | **"
             + signed(s.classBytesChange()) + "** |");
        line();
        line("The category changes add up to the change in uncompressed class-file bytes.");
        line();

        line("### Bytecode attribution");
        line();
        line("Parts of classes attributed to a category other than the class's own (see Method).");
        line();
        line("| Class | Build | Class category | Carved to | Carved members | Bytes |");
        line("|---|---|---|---|---|---|");
        boolean any = carveRows(s, "Baseline_Build", s.baseline());
        any |= carveRows(s, "Feature build", s.feature());
        if (!any) {
            line("| — | — | — | — | — | — |");
        }
        line();

        line("### Largest changes by top-level class");
        line();
        line("Each row is a top-level class together with its nested classes; the " + LARGEST_CHANGES
             + " largest absolute changes.");
        line();
        line("| Class | Category | Baseline_Build (classes) | Feature build (classes) | Change |");
        line("|---|---|---|---|---|");
        for (ServiceComparison.ClassGroupChange group : s.largestChanges(LARGEST_CHANGES)) {
            line("| `" + relative(s, group.name()) + "` | " + group.category().label() + " | "
                 + n(group.baselineBytes()) + " (" + group.baselineClasses() + ") | " + n(group.featureBytes()) + " ("
                 + group.featureClasses() + ") | " + signed(group.change()) + " |");
        }
        line();

        line("### Bytes per package (Requirement 36.1)");
        line();
        line("| Package | Baseline_Build classes | Baseline_Build bytes | Feature build classes | Feature build bytes "
             + "| Change |");
        line("|---|---|---|---|---|---|");
        Set<String> packages = new TreeSet<>(s.baseline().packages().keySet());
        packages.addAll(s.feature().packages().keySet());
        for (String pkg : packages) {
            ServiceSizes.PackageSize before = s.baseline().packages().get(pkg);
            ServiceSizes.PackageSize after = s.feature().packages().get(pkg);
            long beforeBytes = before == null ? 0 : before.bytes();
            long afterBytes = after == null ? 0 : after.bytes();
            line("| `" + pkg + "` | " + n(before == null ? 0 : before.classes()) + " | " + n(beforeBytes) + " | "
                 + n(after == null ? 0 : after.classes()) + " | " + n(afterBytes) + " | "
                 + signed(afterBytes - beforeBytes) + " |");
        }
        line();
    }

    private boolean carveRows(ServiceComparison s, String build, ServiceSizes sizes) {
        boolean any = false;
        for (ClassAttribution attribution : sizes.classes()) {
            for (ClassAttribution.Carve carve : attribution.carves()) {
                any = true;
                List<String> members = new ArrayList<>();
                if (!carve.methods().isEmpty()) {
                    members.add(plural(carve.methods().size(), "method"));
                }
                if (!carve.fields().isEmpty()) {
                    members.add(plural(carve.fields().size(), "static field") + " (" + codeList(carve.fields())
                                + ")");
                }
                if (carve.staticInitializerSegments() > 0) {
                    members.add(plural(carve.staticInitializerSegments(), "`<clinit>` segment"));
                }
                line("| `" + relative(s, attribution.className()) + "` | " + build + " | "
                     + attribution.category().label() + " | " + carve.category().label() + " | "
                     + String.join(", ", members) + " | " + n(carve.bytes()) + " |");
            }
        }
        return any;
    }

    private void modules() {
        line("## Runtime modules (Requirement 36.6)");
        line();
        line("Compressed JAR bytes of the `software.amazon.awssdk` runtime dependencies of the reported services that "
             + "the feature build adds, changes or drops. A module absent from a build is recorded as 0 bytes there. "
             + "These are not part of the per-service totals above.");
        line();
        line("| Module | Status | Baseline_Build | Feature build | Change |");
        line("|---|---|---|---|---|");
        List<String> unchanged = new ArrayList<>();
        Map<ModuleComparison.Status, String> statusText = new EnumMap<>(ModuleComparison.Status.class);
        statusText.put(ModuleComparison.Status.ADDED, "added");
        statusText.put(ModuleComparison.Status.CHANGED, "changed");
        statusText.put(ModuleComparison.Status.DROPPED, "no longer a dependency");
        for (ModuleComparison.Row row : modules.rows()) {
            if (row.status() == ModuleComparison.Status.UNCHANGED) {
                unchanged.add(row.artifactId());
                continue;
            }
            line("| `" + row.artifactId() + "` | " + statusText.get(row.status()) + " | " + n(row.baselineBytes())
                 + " | " + n(row.featureBytes()) + " | " + signed(row.featureBytes() - row.baselineBytes()) + " |");
        }
        line();
        line("Unchanged (same content in both builds): " + (unchanged.isEmpty() ? "none" : codeList(unchanged)) + ".");
        line();
    }

    private void method() {
        line("## Method");
        line();
        line("- **Inputs.** Each service's main JAR (no sources or javadoc JARs) and its `software.amazon.awssdk` "
             + "runtime dependencies, from both builds. The Baseline_Build is built from source with the same JDK, "
             + "Maven and compiler options as the feature build, so the released `2.49.6` JAR (built by the release "
             + "pipeline with JDK 17) is not used.");
        line("- **Measures (36.1).** Compressed size is the JAR file's size. Uncompressed bytes, class counts and "
             + "bytes per package cover every `.class` entry, nested, anonymous and synthetic classes included.");
        line("- **Categories (36.2).** A service package is a package with a `Default<Prefix>Client`; `S` is a "
             + "class's top-level simple name and `sub` the first package segment below the service package. The "
             + "first matching rule assigns each class to exactly one category:");
        line("  1. Removed marshallers and unmarshallers: `sub` is `transform`, or `S` ends with `Marshaller` or "
             + "`Unmarshaller`.");
        line("  2. Schemas: `S` is `<Prefix>Schemas*`, `<Prefix>ServiceSchemas*` or `<Prefix>SchemaIndex`.");
        line("  3. Type_Registries: `S` is `<Prefix>*TypeRegistry` or `<Prefix>*ErrorRegistry`.");
        line("  4. Client classes: classes in the service package itself, in `paginators`, `waiters` or "
             + "`batchmanager`, and `<Prefix>Operations`.");
        line("  5. Generated_Model_Class classes: `sub` is `model`, except `*Copier` and `<Prefix>SharedSerde` "
             + "(structures, unions, exceptions, builders, enums and their nested classes).");
        line("  6. Other: everything else, including endpoints, auth, `internal`, `jmespath`, `*Copier` and "
             + "`<Prefix>SharedSerde`.");
        line("- **Bytecode attribution.** Two categories are measured inside classes with ASM. A carve removes "
             + "members from a class and writes the class again with a fresh constant pool; its bytes are the "
             + "difference, so they include the `method_info`/`field_info` structures and the constant-pool "
             + "entries and bootstrap methods only those members use. The class keeps its own category for the "
             + "remaining bytes, so every byte is counted once and the category changes add up exactly.");
        line("  - Type_Registries: each static `ErrorRegistry`/`TypeRegistry` field of a class in another category "
             + "(`<Prefix>Operations.ERROR_REGISTRY`), with the `<clinit>` code that builds it and the lambdas "
             + "that code creates.");
        line("  - Removed exception-mapping code: in client classes, each method whose descriptor or signature "
             + "mentions `ExceptionMetadata`, whose code uses `ExceptionMetadata` or its builder, or that is a "
             + "`lambda$*(String)Optional` error-code mapper, with the lambdas those methods create. The "
             + "statements inside each operation method that pass the mapper on stay with the client classes.");
        line("- **Requirement 36.3/36.8.** A service fails when its feature compressed JAR is larger than the "
             + "Baseline_Build's; the summary then lists the categories with a net increase.");
    }

    private String relative(ServiceComparison s, String internalName) {
        for (String servicePackage : s.feature().servicePackages()) {
            if (internalName.startsWith(servicePackage + "/")) {
                return internalName.substring(servicePackage.length() + 1).replace('/', '.');
            }
        }
        return internalName.replace('/', '.');
    }

    private static List<String> dotted(List<String> internalNames) {
        List<String> result = new ArrayList<>();
        for (String name : internalNames) {
            result.add(name.replace('/', '.'));
        }
        return result;
    }

    private static String labels(List<SizeCategory> categories) {
        List<String> result = new ArrayList<>();
        for (SizeCategory category : categories) {
            result.add(category.label());
        }
        return result.isEmpty() ? "none" : String.join(", ", result);
    }

    private static String codeList(List<String> items) {
        return "`" + String.join("`, `", items) + "`";
    }

    private static String plural(int count, String noun) {
        return count + " " + noun + (count == 1 ? "" : "s");
    }

    static String n(long value) {
        return String.format(Locale.ROOT, "%,d", value);
    }

    static String signed(long value) {
        return value > 0 ? "+" + n(value) : n(value);
    }

    static String change(long change, long base) {
        if (base == 0) {
            return signed(change);
        }
        return signed(change) + String.format(Locale.ROOT, " (%+.1f%%)", 100.0 * change / base);
    }

    private void line(String text) {
        out.append(text).append(NL);
    }

    private void line() {
        out.append(NL);
    }
}
