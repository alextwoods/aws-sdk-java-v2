package software.amazon.awssdk.benchmark.e2e;

import java.io.IOException;
import java.io.InputStream;
import java.security.GeneralSecurityException;
import java.security.KeyStore;
import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManager;
import javax.net.ssl.TrustManagerFactory;
import software.amazon.awssdk.http.TlsTrustManagersProvider;

/**
 * The self-signed key pair the mock server presents, and the trust manager that accepts it.
 *
 * <h2>Why the mock server needs TLS at all</h2>
 *
 * <p>Every DynamoDB scenario runs over plain HTTP, which keeps the measurement about the SDK rather
 * than about the JDK's cipher suites. The S3 streaming scenarios cannot: over HTTP with a request
 * body, {@code ChecksumUtil.isPayloadSigning} forces payload signing on regardless of
 * {@code PAYLOAD_SIGNING_ENABLED}, so stock v2 signs a {@code PutObject} with aws-chunked framing
 * while the bridge refuses the request outright ({@code compatability_issues.md} §13.2). The two arms
 * would not be doing the same work, which is the one thing a paired comparison must not allow.
 *
 * <p>Over HTTPS both arms send {@code UNSIGNED-PAYLOAD} and the raw bytes, which is also what a real
 * {@code PutObject} does. TLS costs both arms the same, and it costs them in the transport rather than
 * in the pipeline — the layer this benchmark is not comparing, since both arms share it.
 *
 * <h2>Why a committed keystore</h2>
 *
 * <p>Generating a certificate at startup would need a certificate builder the JDK does not expose
 * publicly. The alternative — a trust-all {@code TrustManager} — would make the client skip
 * certificate validation, which is measurable work a real client does. So the key pair is generated
 * once by {@code keytool}, committed, and trusted explicitly:
 *
 * <pre>
 *   keytool -genkeypair -alias benchmark -keyalg EC -groupname secp256r1 \
 *           -sigalg SHA256withECDSA -validity 36500 \
 *           -dname "CN=benchmark-mock-server, OU=javav2-smithy-java-bridge, O=benchmark" \
 *           -ext "SAN=dns:localhost,ip:127.0.0.1" \
 *           -keystore src/main/resources/benchmark-tls/benchmark.p12 -storetype PKCS12 \
 *           -storepass benchmark -keypass benchmark
 * </pre>
 *
 * <p>It is a throwaway credential for a loopback server that serves generated bytes: the private key
 * is in the repository on purpose, and it authenticates nothing else. The SAN covers
 * {@code 127.0.0.1} so hostname verification passes without being disabled.
 */
final class BenchmarkTls {

    private static final String RESOURCE = "/benchmark-tls/benchmark.p12";
    /** Not a secret; see the class javadoc. */
    static final String PASSWORD = "benchmark";

    private BenchmarkTls() {
    }

    /** The server's key pair and certificate, also used by the client as its trust store. */
    static KeyStore keyStore() {
        try (InputStream in = BenchmarkTls.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                throw new IllegalStateException(
                    RESOURCE + " is not on the classpath; the benchmark jar was built without it");
            }
            KeyStore store = KeyStore.getInstance("PKCS12");
            store.load(in, PASSWORD.toCharArray());
            return store;
        } catch (IOException | GeneralSecurityException e) {
            throw new IllegalStateException("could not load " + RESOURCE, e);
        }
    }

    /**
     * Trusts exactly the mock server's certificate and nothing else.
     *
     * <p>Deliberately not a trust-all manager: the client should do the same path validation it does
     * against a real endpoint, so that work stays inside the measurement.
     */
    static TlsTrustManagersProvider trustManagersProvider() {
        return BenchmarkTls::trustManagers;
    }

    private static TrustManager[] trustManagers() {
        try {
            TrustManagerFactory factory =
                TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
            factory.init(keyStore());
            return factory.getTrustManagers();
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException("could not build a trust manager for " + RESOURCE, e);
        }
    }

    /**
     * Context for the harness's own control-plane clients — the readiness probe, the {@code /stats}
     * reader and the fault injector — which are plain {@link java.net.http.HttpClient}s and would
     * otherwise validate against the JDK default trust store and fail the handshake.
     *
     * <p>Safe to install unconditionally: an {@code SSLContext} is only consulted for {@code https}
     * URIs, so the plain-HTTP DynamoDB runs are unaffected.
     *
     * <p>Built once and cached, because {@link ServerStats} polls around every measured window and
     * initializing a context there would put its class loading next to the measurement.
     */
    static SSLContext sslContext() {
        SSLContext context = cachedContext;
        if (context == null) {
            synchronized (BenchmarkTls.class) {
                context = cachedContext;
                if (context == null) {
                    context = newSslContext();
                    cachedContext = context;
                }
            }
        }
        return context;
    }

    private static volatile SSLContext cachedContext;

    private static SSLContext newSslContext() {
        try {
            SSLContext context = SSLContext.getInstance("TLS");
            context.init(null, trustManagers(), null);
            return context;
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException("could not build an SSLContext for " + RESOURCE, e);
        }
    }
}
